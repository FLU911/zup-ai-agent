# Наблюдатель за входящей почтой 1С.
#
# Каждые N секунд просит агента выполнить один тик по регламенту
# ЦИКЛ-мониторинг-почты.md: забрать почту с сервера, сравнить входящие
# с обработанные.json, выполнить задание из нового письма и ответить.
#
# Работает с обоими инструментами — Claude Code и OpenCode:
#   .\следить-за-почтой.ps1                      # claude, интервал из настроек
#   .\следить-за-почтой.ps1 -Инструмент opencode
#   .\следить-за-почтой.ps1 -Интервал 300 -Один  # один тик и выход
#
# Останавливается по Ctrl+C.

param(
    [ValidateSet('claude', 'opencode')]
    [string]$Инструмент = 'claude',

    [int]$Интервал = 0,

    [string]$Модель = '',

    [switch]$Один
)

$ErrorActionPreference = 'Stop'
$ПапкаПочты = Split-Path -Parent $MyInvocation.MyCommand.Path
$КореньПроекта = Split-Path -Parent $ПапкаПочты

# ── настройки ────────────────────────────────────────────────────────
$ФайлНастроек = Join-Path $ПапкаПочты 'настройки.json'
if (-not (Test-Path $ФайлНастроек)) {
    Write-Host "Нет файла настройки.json." -ForegroundColor Yellow
    Write-Host "Скопируйте настройки.example.json в настройки.json и впишите свои адреса."
    exit 1
}
$Настройки = Get-Content $ФайлНастроек -Raw -Encoding UTF8 | ConvertFrom-Json
if ($Интервал -le 0) {
    $Интервал = if ($Настройки.'интервал-проверки-секунд') { [int]$Настройки.'интервал-проверки-секунд' } else { 60 }
}

$Задание = @"
Выполни один тик почтового цикла строго по регламенту почта/ЦИКЛ-мониторинг-почты.md.
Коротко: подключить клиент тестирования, забрать почту командой «Отправить и получить»
в журнале «Взаимодействия», сравнить входящие с почта/обработанные.json.
Если есть новое письмо с адреса из белого списка в почта/настройки.json — выполнить
задание по правилам CLAUDE.md, ответить письмом, убедиться что оно ушло, обновить
почта/обработанные.json и почта/журнал.md.
Новых писем нет — ничего не делать и ничего не писать.
"@

function Тик {
    $метка = Get-Date -Format 'HH:mm:ss'
    Write-Host "[$метка] проверяю почту ($Инструмент)" -ForegroundColor DarkGray
    Push-Location $КореньПроекта
    try {
        if ($Инструмент -eq 'claude') {
            & claude -p $Задание
        }
        else {
            $аргументы = @('run', '--auto', '--dir', $КореньПроекта)
            if ($Модель) { $аргументы += @('-m', $Модель) }
            $аргументы += $Задание
            & opencode @аргументы
        }
    }
    catch {
        Write-Host "[$метка] тик не удался: $($_.Exception.Message)" -ForegroundColor Red
    }
    finally {
        Pop-Location
    }
}

if ($Один) {
    Тик
    return
}

Write-Host "Слежу за почтой: $Инструмент, каждые $Интервал с. Ctrl+C — остановить." -ForegroundColor Cyan
while ($true) {
    Тик
    Start-Sleep -Seconds $Интервал
}
