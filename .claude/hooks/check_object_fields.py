#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""PreToolUse: не даёт записать объект, у которого не заполнено главное.

Общий предохранитель на создание любого объекта в базе. Частные хуки
(приём на работу, штатное расписание) проверяют своё, этот — то, без чего
запись бессмысленна у всех:

  документ    — организация, дата документа и тот, по кому документ;
  справочник  — наименование.

Зачем. Документ без организации попадает не в тот учёт и не находится
отбором; дата документа подставляется сегодняшняя, а агент почти всегда
работает задним числом — закрывает февраль, а документ ложится сентябрём.
Обе ошибки видны только потом, на сверке.

Как узнаём, какой объект открыт. У инструментов формы нет параметра
объекта: они работают с активным окном. Зато форма почти всегда
открывается навигационной ссылкой `e1cib/list/Документ.Отпуск` — из неё
имя объекта и берём. По имени в таблице `требования-объектов.json`
находим, что именно требовать; таблица собрана из словарей действий
скриптом drafts/инструменты/собрать-требования-объектов.py, имена в ней
настоящие, не выдуманные. Если объект опознать не удалось (форму открыли
вводом на основании, из другого документа, по кнопке в списке) —
работает общее правило: проводят документ — спроси про организацию,
записывают элемент — про наименование или организацию.

Проверка одна и в конце, на кнопке записи. Спрашивать на каждом поле
нельзя: человек начнёт жать «да» не глядя, и все хуки разом перестанут
работать.

Требование закрывается двумя способами: агент ввёл значение сам или
прочитал поле через `get_form_element_data`. Второе — не поблажка:
организация и дата часто подставляются формой по умолчанию, и правило
4a CLAUDE.md всё равно требует проверить, что в поле стоит нужное.
Хук просто отказывается верить, что там нужное, пока никто не смотрел.

Поля табличных частей (вызов с `table_name`) не в счёт: обязательным
может быть только поле шапки.

ЗЕРКАЛО: то же самое для OpenCode — .opencode/plugin/object-fields.js.
Правишь одно, правь второе, потом прогони проверку:
    python drafts/инструменты/проверить-хук-объектов.py
"""
import io
import json
import os
import re
import sys
import tempfile
import time

# Консоль Windows по умолчанию cp1251 — без этого причина приходит
# крякозябрами.
try:
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8",
                                  errors="replace", newline="")
except Exception:
    pass


ТАБЛИЦА = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       "требования-объектов.json")

# Из навигационной ссылки: e1cib/list/Документ.Отпуск,
# e1cib/data/Справочник.Должности.Форма.ФормаЭлемента
ССЫЛКА = re.compile(
    r"(Документ|Справочник|ПланВидовРасчета|РегистрСведений|Обработка|Отчет)"
    r"\.([A-Za-zА-Яа-яЁё0-9_]+)")

# Действия, после которых в поле появляется значение.
ВВОД = ("set_value", "input_text", "select_from_dropdown", "set_checkbox",
        "set_radio_button", "open_choice_form")

# Кнопки, на которых объект попадает в базу.
КНОПКИ_ПРОВЕДЕНИЯ = ("ФормаПровести", "ФормаПровестиИЗакрыть",
                     "КомандаПровести", "КомандаПровестиИЗакрыть")
КНОПКИ_ЗАПИСИ = ("ФормаЗаписать", "ФормаЗаписатьИЗакрыть",
                 "КомандаЗаписать", "КомандаЗаписатьИЗакрыть", "КомандаОК")

# Начали новый объект — накопленное больше не про него.
КНОПКИ_СОЗДАНИЯ = ("ФормаСоздать", "КомандаСоздать", "ФормаСкопировать")
КНОПКИ_ЗАКРЫТИЯ = ("ФормаЗакрыть", "КомандаЗакрыть", "ФормаОтменаПроведения")

# Общее правило для неопознанного объекта.
ФОЛБЭК_ДОКУМЕНТ = [["в какой организации",
                    ["Организация", "ОрганизацияПлательщик", "Владелец"]]]
ФОЛБЭК_ЗАПИСЬ = [["наименование или организация",
                  ["Наименование", "ФИО", "НаименованиеПолное",
                   "Организация", "Владелец"]]]

СОСТОЯНИЕ = os.path.join(tempfile.gettempdir(), "zup-agent-object.json")
ЖИВЁТ = 2 * 60 * 60  # документ с подбором сотрудника занимает и час


def требования_объектов():
    try:
        with io.open(ТАБЛИЦА, encoding="utf-8") as f:
            return json.load(f).get("объекты") or {}
    except Exception:
        return {}  # нет таблицы — останется общее правило


def прочитать():
    try:
        with io.open(СОСТОЯНИЕ, encoding="utf-8") as f:
            s = json.load(f)
    except Exception:
        return None
    if not isinstance(s, dict):
        return None
    if time.time() - s.get("начато", 0) > ЖИВЁТ:
        return None
    return s


def записать(s):
    try:
        with io.open(СОСТОЯНИЕ, "w", encoding="utf-8") as f:
            json.dump(s, f, ensure_ascii=False)
    except Exception:
        pass  # не смогли — не мешаем работать


def забыть():
    try:
        os.remove(СОСТОЯНИЕ)
    except Exception:
        pass


def чистое(объект=None, спрошено=False):
    # «спрошено» — вопрос по этому объекту уже задавали. Второе нажатие
    # той же кнопки пропускаем: человек ответил, переспрашивать нечего,
    # иначе на «да» приходит тот же вопрос ещё раз.
    return {"начато": time.time(), "объект": объект,
            "заполнено": [], "проверено": [], "спрошено": спрошено}


def действия(tool_name, tool_input):
    """[(действие, имя элемента, имя таблицы), ...] — что делает вызов."""
    out = []

    if tool_name.endswith("manage_form_elements"):
        out.append((tool_input.get("action") or "",
                    tool_input.get("element_name") or "",
                    tool_input.get("table_name") or ""))

    elif tool_name.endswith("execute_form_actions"):
        raw = tool_input.get("actions_json") or "[]"
        try:
            lst = json.loads(raw) if isinstance(raw, str) else raw
        except Exception:
            return out  # не наше дело — пусть падает штатно
        if not isinstance(lst, list):
            return out
        for a in lst:
            if isinstance(a, dict):
                out.append((a.get("action") or "", a.get("element_name") or "",
                            a.get("table_name") or ""))

    return out


def чего_нет(требуется, закрыто):
    есть = set(закрыто)
    return [(вопрос, имена) for вопрос, имена in требуется
            if not есть.intersection(имена)]


def причина(объект, нет, документ):
    перечень = "\n".join("  - %s (%s)" % (вопрос, " / ".join(имена))
                         for вопрос, имена in нет)
    что = ("«%s»" % объект.split(".")[-1] if объект
           else ("Документ" if документ else "Элемент справочника"))
    действие = "проведением" if документ else "записью"
    return (
        "%s: перед %s не заполнено главное.\n" % (что, действие)
        + перечень + "\n"
        "Эти значения берутся из задания, а не подбираются агентом. "
        "Названы в задании — заполни и повтори. Не названы — остановись и "
        "спроси человека, не подставляй по смыслу: организация и дата "
        "документа определяют, в чей учёт и в какой месяц он ляжет, а "
        "видно это станет только на сверке.\n"
        "Если поле уже заполнено формой по умолчанию — прочитай его "
        "через `get_form_element_data`, убедись, что там нужное значение, "
        "и повтори запись: прочитанное поле хук считает закрытым.\n"
        "В неинтерактивном запуске это отказ — запиши статус "
        "«нужно-согласие» и доложи человеку."
    )


def main():
    try:
        data = json.loads(sys.stdin.buffer.read().decode("utf-8", errors="replace"))
    except Exception:
        return  # не смогли разобрать — не мешаем

    tool_name = data.get("tool_name") or ""
    tool_input = data.get("tool_input") or {}
    if not isinstance(tool_input, dict):
        return

    состояние = прочитать() or чистое()

    # 1. Навигационная ссылка — единственное место, где виден объект.
    if tool_name.endswith("window_management"):
        действие = tool_input.get("action") or ""
        if действие == "open_navigation":
            m = ССЫЛКА.search(tool_input.get("navigation_link") or "")
            if m:
                записать(чистое("%s.%s" % (m.group(1), m.group(2))))
        elif действие == "close":
            забыть()
        return

    # 2. Прочитанное поле закрывает требование не хуже введённого.
    if tool_name.endswith("get_form_element_data"):
        имя = tool_input.get("element_name") or ""
        if имя and имя not in состояние["проверено"]:
            состояние["проверено"].append(имя)
            записать(состояние)
        return

    пары = действия(tool_name, tool_input)
    if not пары:
        return

    # 3. Копим заполненные поля шапки. Копим всегда: объект мог быть
    #    опознан раньше, а мог не опознаться вовсе.
    изменилось = False
    for действие, имя, имя_таблицы in пары:
        if имя_таблицы or not имя:
            continue  # поле табличной части обязательным не бывает
        if действие in ВВОД and имя not in состояние["заполнено"]:
            состояние["заполнено"].append(имя)
            изменилось = True

    создают = any(действие == "create_new"
                  or (действие == "click_button" and имя in КНОПКИ_СОЗДАНИЯ)
                  for действие, имя, _ in пары)
    пишут = [имя for действие, имя, _ in пары
             if действие == "click_button"
             and имя in КНОПКИ_ПРОВЕДЕНИЯ + КНОПКИ_ЗАПИСИ]
    закрывают = any(действие == "click_button" and имя in КНОПКИ_ЗАКРЫТИЯ
                    for действие, имя, _ in пары)

    if пишут:
        pass
    elif создают or закрывают:
        # Новая карточка или уход с формы: объект помним, поля забываем.
        записать(чистое(состояние["объект"]))
        return
    else:
        if изменилось:
            записать(состояние)
        return

    # 4. Проверяем на записи.
    объект = состояние["объект"]
    if состояние.get("спрошено"):
        записать(чистое(объект))
        return
    закрыто = состояние["заполнено"] + состояние["проверено"]
    документ = any(имя in КНОПКИ_ПРОВЕДЕНИЯ for имя in пишут)

    правила = требования_объектов().get(объект or "", {}).get("требуется")
    if правила is None:
        if объект:
            # Объект опознан, но в таблице его нет: свой хук, отчёт,
            # обработка. Молчим, чтобы не спрашивать дважды.
            записать(чистое(объект))
            return
        правила = ФОЛБЭК_ДОКУМЕНТ if документ else ФОЛБЭК_ЗАПИСЬ

    нет = чего_нет(правила, закрыто)
    записать(чистое(объект, спрошено=bool(нет)))
    if not нет:
        return

    out = {
        "hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "permissionDecision": "ask",
            "permissionDecisionReason": причина(объект, нет, документ),
        }
    }
    sys.stdout.write(json.dumps(out, ensure_ascii=False))


if __name__ == "__main__":
    main()
