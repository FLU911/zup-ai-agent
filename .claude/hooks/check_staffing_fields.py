#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""PreToolUse: не даёт завести позицию штатного расписания без главного.

Шесть значений задаёт человек, а не агент: организация, подразделение,
дата утверждения, должность, оклад и количество ставок. Ошибка здесь
дороже, чем в кадровом документе: позиция — основание для приёма, и
неверный оклад или подразделение расходятся дальше по всем принятым
на неё сотрудникам.

Устройство то же, что у check_hiring_fields: копим заполненные поля,
проверяем один раз — на кнопке сохранения. Спрашивать на каждом из шести
полей нельзя, человек начнёт жать «да» не глядя.

Одно требование — несколько допустимых имён. Позиция заводится не одной
формой: у документа «Изменение штатного расписания» организация лежит
в `Организация`, а на форме самой позиции та же организация называется
`Владелец`; дата — `ДатаВступленияВСилу` у документа и `ДатаУтверждения`
у позиции. Поэтому под каждый вопрос человека — список имён, любого
из них достаточно.

Имена сверены со словарями drafts/словари/ШтатноеРасписание.feature
и ИзменениеШтатногоРасписания.feature. Ничего не выдумано.

Чего этот хук НЕ ловит:
  - `ДатаВступленияВСилу` есть ещё у «Утверждения тарифной сетки»;
    там вопрос про должность и оклад будет лишним.
  - состав формы позиции документа (ОбщаяФорма.ФормаСтроки...) снят
    не полностью: словарь подтвердил на ней только `КоличествоСтавок`
    и `КомандаОК`. Если оклад и должность на ней называются иначе, чем
    в справочнике, хук их не увидит. Снять форму живьём и дописать имена
    в списки ниже — работа на одну операцию.

ЗЕРКАЛО: то же самое для OpenCode — .opencode/plugin/staffing-fields.js.
Правишь одно, правь второе.
"""
import io
import json
import os
import sys
import tempfile
import time

# Консоль Windows по умолчанию cp1251 — без этого причина приходит
# крякозябрами.
try:
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8",
                                  errors="replace", newline="")
except Exception:
    pass


# Вопрос человеку → имена элементов, любое из которых его закрывает.
ОБЯЗАТЕЛЬНЫЕ = (
    ("в какой организации", ("Организация", "Владелец")),
    ("в каком подразделении", ("Подразделение",)),
    ("с какой даты утверждена", ("ДатаУтверждения", "ДатаВступленияВСилу")),
    ("на какую должность", ("Должность",)),
    ("какой оклад", ("Оклад",)),
    ("сколько ставок", ("КоличествоСтавок",)),
)

# Поля, которые есть только у штатного расписания: по ним узнаём, что
# работаем именно с позицией, а не с другим документом.
МАРКЕРЫ = ("ДатаУтверждения", "Оклад", "ДатаВступленияВСилу")

# Сохранение позиции: КомандаОК закрывает форму строки документа,
# остальное — проведение самого документа (ловушка 5 словаря
# ИзменениеШтатногоРасписания: здесь ФормаПровести видима и работает).
КНОПКИ_СОХРАНЕНИЯ = (
    "КомандаОК",
    "ФормаПровести",
    "ФормаПровестиИЗакрыть",
    "КомандаПровести",
    "КомандаПровестиИЗакрыть",
)

# Ушли, ничего не сохранив — накопленное больше не про эту позицию.
КНОПКИ_ЗАКРЫТИЯ = (
    "ФормаЗакрыть",
    "КомандаЗакрыть",
    "ФормаОтменаПроведения",
)

ВВОД = ("set_value", "input_text")

СОСТОЯНИЕ = os.path.join(tempfile.gettempdir(), "zup-agent-shr.json")
ЖИВЁТ = 2 * 60 * 60


def прочитать():
    try:
        with io.open(СОСТОЯНИЕ, encoding="utf-8") as f:
            s = json.load(f)
    except Exception:
        return None
    if not isinstance(s, dict):
        return None
    if time.time() - s.get("начато", 0) > ЖИВЁТ:
        return None
    return s


def записать(s):
    try:
        with io.open(СОСТОЯНИЕ, "w", encoding="utf-8") as f:
            json.dump(s, f, ensure_ascii=False)
    except Exception:
        pass  # не смогли — не мешаем работать


def забыть():
    try:
        os.remove(СОСТОЯНИЕ)
    except Exception:
        pass


ВСЕ_ИМЕНА = {имя for _, имена in ОБЯЗАТЕЛЬНЫЕ for имя in имена}


def действия(tool_name, tool_input):
    """[(действие, имя элемента), ...] — что этот вызов делает с формой."""
    out = []

    if tool_name.endswith("manage_form_elements"):
        out.append((tool_input.get("action") or "",
                    tool_input.get("element_name") or ""))

    elif tool_name.endswith("execute_form_actions"):
        raw = tool_input.get("actions_json") or "[]"
        try:
            lst = json.loads(raw) if isinstance(raw, str) else raw
        except Exception:
            return out  # не наше дело — пусть падает штатно
        if not isinstance(lst, list):
            return out
        for a in lst:
            if isinstance(a, dict):
                out.append((a.get("action") or "", a.get("element_name") or ""))

    return out


def чего_нет(заполнено):
    есть = set(заполнено)
    return [(вопрос, имена) for вопрос, имена in ОБЯЗАТЕЛЬНЫЕ
            if not есть.intersection(имена)]


def main():
    try:
        data = json.loads(sys.stdin.buffer.read().decode("utf-8", errors="replace"))
    except Exception:
        return  # не смогли разобрать — не мешаем

    tool_name = data.get("tool_name") or ""
    tool_input = data.get("tool_input") or {}
    if not isinstance(tool_input, dict):
        return

    пары = действия(tool_name, tool_input)
    if not пары:
        return

    состояние = прочитать() or {"начато": time.time(), "заполнено": [],
                                "штатное": False}

    # 1. Копим заполненные поля с самого начала: организацию и
    #    подразделение агент вводит раньше, чем оклад и дату.
    изменилось = False
    for действие, имя in пары:
        if действие not in ВВОД:
            continue
        if имя in ВСЕ_ИМЕНА and имя not in состояние["заполнено"]:
            состояние["заполнено"].append(имя)
            изменилось = True
        if имя in МАРКЕРЫ and not состояние["штатное"]:
            состояние["штатное"] = True
            изменилось = True
    if изменилось:
        записать(состояние)

    # 2. Проверяем на сохранении.
    сохраняют = any(действие == "click_button" and имя in КНОПКИ_СОХРАНЕНИЯ
                    for действие, имя in пары)
    закрывают = any(действие == "click_button" and имя in КНОПКИ_ЗАКРЫТИЯ
                    for действие, имя in пары)
    if закрывают and not сохраняют:
        забыть()
        return
    if not сохраняют:
        return

    штатное = состояние["штатное"]
    нет = чего_нет(состояние["заполнено"])
    забыть()  # спрашиваем один раз, иначе зациклимся
    if not штатное or not нет:
        return

    перечень = "\n".join("  - %s (%s)" % (вопрос, " / ".join(имена))
                         for вопрос, имена in нет)
    reason = (
        "Позиция штатного расписания: не заполнено то, что задаёт человек.\n"
        + перечень + "\n"
        "Позиция — основание для приёма на работу: неверный оклад или "
        "подразделение разойдутся дальше по всем, кого на неё примут. "
        "Названо в задании — заполни и повтори сохранение. Не названо — "
        "остановись и спроси человека, не подставляй по смыслу.\n"
        "В неинтерактивном запуске это отказ — запиши статус "
        "«нужно-согласие» и доложи человеку."
    )
    out = {
        "hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "permissionDecision": "ask",
            "permissionDecisionReason": reason,
        }
    }
    sys.stdout.write(json.dumps(out, ensure_ascii=False))


if __name__ == "__main__":
    main()
