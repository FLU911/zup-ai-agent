#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""PreToolUse: не даёт провести приём на работу, пока не заполнено главное.

На приёме шесть значений задаёт человек, а не агент: кого, кем, куда,
в какую организацию, по какому графику и с какого числа. Пропущенное поле
здесь стоит дорого: часть из них после проведения меняется только
исправлением документа, а график тянет за собой весь табель и расчёт.

Отличие от check_decision_fields: тот срабатывает на КАЖДОМ вводе в поле
юридической квалификации. Здесь так нельзя — шесть полей за документ
означали бы шесть вопросов подряд, человек начал бы жать «да» не глядя,
и оба хука перестали бы работать. Поэтому проверка одна и в конце:
на кнопке проведения.

Как отличаем приём от других документов. У инструмента нет параметра
формы — он работает с активным окном, и по одному вызову тип документа
не виден. Поэтому хук копит заполненные поля ВСЕГДА, а признаком приёма
считает ввод в `ДатаПриема`: это поле есть только здесь. Копить надо
с самого начала, а не с момента опознания: агент обычно вводит
организацию и сотрудника раньше даты приёма.

Накопленное живёт до первого проведения или закрытия формы — тогда
сбрасывается, чтобы поля одного документа не зачлись следующему.

Слепое пятно, про которое надо знать: если агент не трогал `ДатаПриема`
вообще, проверки не будет. Этот случай ловит сама 1С — дата приёма
обязательна для проведения, и отказ придёт из блока «В окне есть
сообщения пользователю».

ЗЕРКАЛО: то же самое для OpenCode — .opencode/plugin/hiring-fields.js.
Правишь одно, правь второе.
"""
import io
import json
import os
import sys
import tempfile
import time

# Консоль Windows по умолчанию cp1251 — без этого причина приходит
# крякозябрами.
try:
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8",
                                  errors="replace", newline="")
except Exception:
    pass


# Имя элемента формы → как называть его человеку.
# Имена сверены со словарём drafts/словари/ПриемНаРаботу.feature.
ОБЯЗАТЕЛЬНЫЕ = {
    "Сотрудник": "кого принимаем (ФИО)",
    "Должность": "на какую должность",
    "Подразделение": "в какое подразделение",
    "Организация": "в какую организацию",
    "График": "по какому графику работы",
    "ДатаПриема": "с какого числа принять",
}

# Поле, по которому узнаём приём: на других документах его нет.
МАРКЕР = "ДатаПриема"

# Выбор позиции штатного расписания подставляет должность и подразделение
# сам — если она заполнена, считаем эти два закрытыми.
ПОЗИЦИЯ = "ПозицияШтатногоРасписания"
ЗАКРЫВАЕТ = ("Должность", "Подразделение")

КНОПКИ_ПРОВЕДЕНИЯ = (
    "ФормаПровести",
    "ФормаПровестиИЗакрыть",
    "КомандаПровести",
    "КомандаПровестиИЗакрыть",
)

# Ушли с формы, ничего не проведя — накопленное больше не про этот документ.
КНОПКИ_ЗАКРЫТИЯ = (
    "ФормаЗакрыть",
    "КомандаЗакрыть",
    "ФормаОтменаПроведения",
)

ВВОД = ("set_value", "input_text")

СОСТОЯНИЕ = os.path.join(tempfile.gettempdir(), "zup-agent-priem.json")
ЖИВЁТ = 2 * 60 * 60  # приём с подбором позиции занимает и час


def прочитать():
    try:
        with io.open(СОСТОЯНИЕ, encoding="utf-8") as f:
            s = json.load(f)
    except Exception:
        return None
    if not isinstance(s, dict):
        return None
    if time.time() - s.get("взведён", 0) > ЖИВЁТ:
        return None
    return s


def записать(s):
    try:
        with io.open(СОСТОЯНИЕ, "w", encoding="utf-8") as f:
            json.dump(s, f, ensure_ascii=False)
    except Exception:
        pass  # не смогли — не мешаем работать


def забыть():
    try:
        os.remove(СОСТОЯНИЕ)
    except Exception:
        pass


def действия(tool_name, tool_input):
    """[(действие, имя элемента), ...] — что этот вызов делает с формой."""
    out = []

    if tool_name.endswith("manage_form_elements"):
        out.append((tool_input.get("action") or "",
                    tool_input.get("element_name") or ""))

    elif tool_name.endswith("execute_form_actions"):
        raw = tool_input.get("actions_json") or "[]"
        try:
            lst = json.loads(raw) if isinstance(raw, str) else raw
        except Exception:
            return out  # не наше дело — пусть падает штатно
        if not isinstance(lst, list):
            return out
        for a in lst:
            if isinstance(a, dict):
                out.append((a.get("action") or "", a.get("element_name") or ""))

    return out


def чего_нет(заполнено):
    есть = set(заполнено)
    if ПОЗИЦИЯ in есть:
        есть.update(ЗАКРЫВАЕТ)
    return [(имя, вопрос) for имя, вопрос in ОБЯЗАТЕЛЬНЫЕ.items()
            if имя not in есть]


def main():
    try:
        data = json.loads(sys.stdin.buffer.read().decode("utf-8", errors="replace"))
    except Exception:
        return  # не смогли разобрать — не мешаем

    tool_name = data.get("tool_name") or ""
    tool_input = data.get("tool_input") or {}
    if not isinstance(tool_input, dict):
        return

    пары = действия(tool_name, tool_input)
    if not пары:
        return

    состояние = прочитать() or {"взведён": time.time(), "заполнено": [],
                                "приём": False}

    # 1. Копим заполненные поля. Копим ДО того, как узнали тип документа:
    #    агент обычно вводит организацию и сотрудника раньше даты приёма,
    #    и если ждать маркера, эти поля потеряются.
    изменилось = False
    for действие, имя in пары:
        if действие not in ВВОД:
            continue
        if имя in ОБЯЗАТЕЛЬНЫЕ or имя == ПОЗИЦИЯ:
            if имя not in состояние["заполнено"]:
                состояние["заполнено"].append(имя)
                изменилось = True
        if имя == МАРКЕР and not состояние["приём"]:
            состояние["приём"] = True
            изменилось = True
    if изменилось:
        записать(состояние)

    # 2. Проверяем на проведении.
    жмут = any(действие == "click_button" and имя in КНОПКИ_ПРОВЕДЕНИЯ
               for действие, имя in пары)
    закрывают = any(действие == "click_button" and имя in КНОПКИ_ЗАКРЫТИЯ
                    for действие, имя in пары)
    if закрывают and not жмут:
        забыть()  # ушли с формы — накопленное больше не про этот документ
        return
    if not жмут:
        return

    приём = состояние["приём"]
    нет = чего_нет(состояние["заполнено"])
    # Провели что-то — начинаем следующий документ с чистого листа, иначе
    # поля предыдущего зачтутся тому, кто идёт следом.
    забыть()
    if not приём or not нет:
        return

    перечень = "\n".join("  - %s (%s)" % (вопрос, имя) for имя, вопрос in нет)
    reason = (
        "Приём на работу: не заполнено то, что задаёт человек.\n"
        + перечень + "\n"
        "Эти шесть значений берутся из задания, а не подбираются агентом. "
        "Если они названы в задании — заполни и повтори проведение. "
        "Если их там нет — остановись и спроси человека, не угадывай: "
        "график тянет за собой табель и расчёт, а подразделение и "
        "должность после проведения правятся только исправлением "
        "документа.\n"
        "В неинтерактивном запуске это отказ — запиши статус "
        "«нужно-согласие» и доложи человеку."
    )
    out = {
        "hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "permissionDecision": "ask",
            "permissionDecisionReason": reason,
        }
    }
    sys.stdout.write(json.dumps(out, ensure_ascii=False))


if __name__ == "__main__":
    main()
