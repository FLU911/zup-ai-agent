#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""PreToolUse: спрашивает человека, когда агент трогает поле-решение.

Есть поля, где ввод значения — это не ввод данных, а РЕШЕНИЕ: основание
увольнения, статья ТК. Ошибка в них не видна в базе и всплывает через
месяцы, а исправляется уже не агентом.

Повод. 30.08.2026 агент оформил увольнение по заданию из письма и САМ
выбрал основание — п. 3 ч. 1 ст. 77. В задании основания не было.
Формально всё верно, но это юридическая квалификация, и он сделал её
молча: для него это ещё одно поле формы.

Правило «не решай за человека» в скиллах есть. Оно не сработало —
потому что правило словами не удерживает там, где цена ошибки высокая.
Нужен механизм.

Отличие от check_exact_match: тот ЗАПРЕЩАЕТ (формальная ошибка вызова,
чинится добавлением параметра), этот СПРАШИВАЕТ (решение может быть
верным, его должен подтвердить человек).

Что это даёт ночным циклам: в неинтерактивном запуске «спросить»
означает отказ. Цикл получает отказ с причиной и по регламенту обязан
записать статус `нужно-согласие` и доложить — вместо того чтобы решить
самому в три часа ночи.

ЗЕРКАЛО: то же самое для OpenCode — .opencode/plugin/decision-fields.js.
Правишь одно, правь второе, потом прогони сверку:
    python drafts/инструменты/сверить-хуки.py
"""
import io, json, sys

# Консоль Windows по умолчанию cp1251 — без этого причина приходит
# крякозябрами.
try:
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8",
                                  errors="replace", newline="")
except Exception:
    pass


# Имя элемента формы → чем это решение является.
#
# Список намеренно короткий: здесь только юридическая квалификация —
# то, что человек решает, а не считывает из задания. Рутинные поля
# (организация, месяц, сумма, вид начисления) сюда НЕ добавлять: агент
# начнёт спрашивать по десять раз за документ, человек станет жать «да»
# не глядя, и хук перестанет работать вовсе.
#
# Оба имени сверены на живой форме: ОснованиеУвольнения — Увольнение,
# СтатьяТКРФ — ПереводКДругомуРаботодателю.
РЕШЕНИЯ = {
    "ОснованиеУвольнения":
        "основание увольнения — юридическая квалификация, а не данные",
    "СтатьяТКРФ":
        "статья ТК — юридическая квалификация, а не данные",
}


def решения(tool_name, tool_input):
    """Список (имя элемента, чем это является) среди затронутых полей."""
    найдено = []

    def проверить(имя):
        if имя in РЕШЕНИЯ:
            найдено.append((имя, РЕШЕНИЯ[имя]))

    if tool_name.endswith("manage_form_elements"):
        проверить(tool_input.get("element_name") or "")

    elif tool_name.endswith("execute_form_actions"):
        raw = tool_input.get("actions_json") or "[]"
        try:
            actions = json.loads(raw) if isinstance(raw, str) else raw
        except Exception:
            return найдено  # не наше дело — пусть падает штатно
        if not isinstance(actions, list):
            return найдено
        for a in actions:
            if isinstance(a, dict):
                проверить(a.get("element_name") or "")

    return найдено


def main():
    try:
        data = json.loads(sys.stdin.buffer.read().decode("utf-8", errors="replace"))
    except Exception:
        return  # не смогли разобрать — не мешаем

    tool_name = data.get("tool_name") or ""
    tool_input = data.get("tool_input") or {}
    if not isinstance(tool_input, dict):
        return

    найдено = решения(tool_name, tool_input)
    if not найдено:
        return

    перечень = "; ".join("%s — %s" % (имя, чем) for имя, чем in найдено)
    reason = (
        "Поле-решение: " + перечень + ".\n"
        "Значение в таком поле — это решение человека, а не данные задачи. "
        "Если оно названо в задании — подтверди и продолжай. Если ты выбрал "
        "его сам, остановись и спроси: 30.08.2026 агент так же молча выбрал "
        "основание увольнения, которого в задании не было.\n"
        "В неинтерактивном запуске это отказ — запиши статус "
        "«нужно-согласие» и доложи человеку."
    )
    out = {
        "hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "permissionDecision": "ask",
            "permissionDecisionReason": reason,
        }
    }
    sys.stdout.write(json.dumps(out, ensure_ascii=False))


if __name__ == "__main__":
    main()
