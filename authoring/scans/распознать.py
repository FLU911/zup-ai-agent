# -*- coding: utf-8 -*-
"""
Распознавание синтетических сканов документов и сверка с эталоном.

Пара к `generate_scans.py`: тот рисует паспорт, ИНН и СНИЛС и заодно
кладёт в `эталон/` то, что на них написано. Этот скрипт решает обратную
задачу — прочитать реквизиты с картинок и проверить, совпало ли.

Зачем это нужно. Заведение сотрудника по сканам — типовая задача агента,
и «модель посмотрела картинку и что-то заполнила» проверять на глаз
бессмысленно: ошибка в одной цифре ИНН выглядит так же убедительно, как
правильный ответ. Эталон делает из сканов измеримый тест.

Два режима.

  1. РАСПОЗНАТЬ — прочитать реквизиты с картинок самому.
     Нужен tesseract с русским языком и пакет pytesseract:

         pip install pytesseract
         # Windows: https://github.com/UB-Mannheim/tesseract/wiki
         #          при установке отметить Russian
         # Linux:   apt install tesseract-ocr tesseract-ocr-rus

     python распознать.py                       все комплекты
     python распознать.py --комплект 04_Дорохов_Сергей_Владимирович
     python распознать.py --вывод out/           сохранить результат в json

  2. СВЕРИТЬ — сравнить с эталоном то, что прочитал кто-то другой.
     Именно так проверяется агент: модель смотрит картинки, отдаёт json
     с реквизитами, скрипт говорит, где она ошиблась. OCR для этого
     не нужен вообще.

     python распознать.py --сверить ответ-агента.json
     python распознать.py --сверить out/          папка с json по комплектам

Код возврата: 0 — всё сошлось, 1 — есть расхождения или не удалось
распознать. Годится для CI и для прогона бенчмарка.
"""

import argparse
import io
import json
import os
import re
import sys
import unicodedata

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
КОМПЛЕКТЫ = os.path.join(ЗДЕСЬ, "комплекты")
ЭТАЛОН = os.path.join(ЗДЕСЬ, "эталон")

# Поля эталона, которые имеет смысл сверять: то, что агент переносит в 1С.
ПОЛЯ = [
    "surname", "name", "patronymic", "birth", "birthplace",
    "passport_series", "passport_number", "issued_at", "dept_code",
    "inn", "snils",
]

ЧЕЛОВЕЧЕСКИ = {
    "surname": "фамилия",
    "name": "имя",
    "patronymic": "отчество",
    "birth": "дата рождения",
    "birthplace": "место рождения",
    "passport_series": "серия паспорта",
    "passport_number": "номер паспорта",
    "issued_at": "дата выдачи",
    "dept_code": "код подразделения",
    "inn": "ИНН",
    "snils": "СНИЛС",
}


# ─────────────────────────────────────────────────────────────────────
# Контрольные разряды. 1С проверяет их прямо в поле ввода, поэтому
# ошибка в цифре ловится здесь, а не на форме сотрудника.
# ─────────────────────────────────────────────────────────────────────

def инн_верен(инн):
    ц = re.sub(r"\D", "", инн or "")
    if len(ц) != 12:
        return False
    в = [int(x) for x in ц]
    к1 = [7, 2, 4, 10, 3, 5, 9, 4, 6, 8]
    к2 = [3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8]
    n11 = sum(a * b for a, b in zip(к1, в[:10])) % 11 % 10
    n12 = sum(a * b for a, b in zip(к2, в[:11])) % 11 % 10
    return n11 == в[10] and n12 == в[11]


def снилс_верен(снилс):
    ц = re.sub(r"\D", "", снилс or "")
    if len(ц) != 11:
        return False
    сумма = sum(int(ц[i]) * (9 - i) for i in range(9))
    контроль = int(ц[9:])
    if сумма < 100:
        ожидание = сумма
    elif сумма in (100, 101):
        ожидание = 0
    else:
        ожидание = сумма % 101
        if ожидание in (100, 101):
            ожидание = 0
    return ожидание == контроль


# ─────────────────────────────────────────────────────────────────────
# Распознавание
# ─────────────────────────────────────────────────────────────────────

def прочитать_текст(путь):
    """Полный текст страницы через tesseract. None, если OCR недоступен."""
    try:
        import pytesseract
        from PIL import Image
    except ImportError:
        return None
    try:
        картинка = Image.open(путь)
    except Exception as e:
        print("  не открылась картинка %s: %s" % (путь, e))
        return None
    try:
        return pytesseract.image_to_string(картинка, lang="rus")
    except Exception as e:
        print("  tesseract не отработал (%s)." % e)
        return None


def разобрать(текст_паспорта, текст_инн, текст_снилс):
    """Вытаскивает реквизиты из распознанного текста.

    Разбор идёт по виду самих значений, а не по подписям полей: подписи
    на бланке набраны мелко и распознаются хуже всего, а ИНН из двенадцати
    цифр или дата в формате дд.мм.гггг ни с чем не спутаешь.
    """
    п = текст_паспорта or ""
    итог = {}

    даты = re.findall(r"\b(\d{2}[.\s]\d{2}[.\s]\d{4})\b", п)
    даты = [d.replace(" ", ".") for d in даты]
    if даты:
        # на развороте две даты: выдачи (страница 2) и рождения (страница 3)
        итог["issued_at"] = даты[0]
        if len(даты) > 1:
            итог["birth"] = даты[-1]

    код = re.search(r"\b(\d{3}\s?-\s?\d{3})\b", п)
    if код:
        итог["dept_code"] = код.group(1).replace(" ", "")

    серия = re.search(r"\b(\d{2}\s?\d{2})\s+(\d{6})\b", п)
    if серия:
        итог["passport_series"] = серия.group(1)[:2] + " " + серия.group(1)[-2:]
        итог["passport_number"] = серия.group(2)
    else:
        номер = re.search(r"\b(\d{6})\b", п)
        if номер:
            итог["passport_number"] = номер.group(1)

    фио = re.findall(r"\b([А-ЯЁ][А-ЯЁ]{2,})\b", п)
    фио = [с for с in фио if с not in ("РОССИЙСКАЯ", "ФЕДЕРАЦИЯ", "ПАСПОРТ", "ОБРАЗЕЦ", "RUSSIA")]
    if len(фио) >= 3:
        итог["surname"], итог["name"], итог["patronymic"] = фио[0].title(), фио[1].title(), фио[2].title()

    место = re.search(r"(гор\.|г\.|с\.|пос\.)\s*([А-ЯЁ][а-яё\- ]+)", п)
    if место:
        итог["birthplace"] = (место.group(1) + " " + место.group(2)).strip()

    инн = re.search(r"\b(\d{12})\b", текст_инн or "")
    if инн:
        итог["inn"] = инн.group(1)

    снилс = re.search(r"\b(\d{3}\s?-\s?\d{3}\s?-\s?\d{3}\s\d{2})\b", текст_снилс or "")
    if снилс:
        итог["snils"] = re.sub(r"\s*-\s*", "-", снилс.group(1))

    return итог


def распознать_комплект(папка):
    print("распознаю %s" % os.path.basename(папка))
    тексты = []
    for имя in ("паспорт.png", "инн.png", "снилс.png"):
        путь = os.path.join(папка, имя)
        тексты.append(прочитать_текст(путь) if os.path.exists(путь) else None)
    if all(т is None for т in тексты):
        return None
    return разобрать(*тексты)


# ─────────────────────────────────────────────────────────────────────
# Сверка с эталоном
# ─────────────────────────────────────────────────────────────────────

def нормализовать(значение):
    if значение is None:
        return ""
    с = unicodedata.normalize("NFKC", str(значение)).strip().lower()
    с = с.replace("ё", "е")
    return re.sub(r"[\s\-]+", "", с)


def сверить(прочитано, эталон, имя_комплекта):
    расхождения = []
    for поле in ПОЛЯ:
        было = эталон.get(поле)
        стало = прочитано.get(поле)
        if нормализовать(было) != нормализовать(стало):
            расхождения.append((поле, было, стало))

    print("\n%s" % имя_комплекта)
    if not расхождения:
        print("  всё сошлось: %d полей" % len(ПОЛЯ))
    else:
        for поле, было, стало in расхождения:
            print("  %-18s эталон: %-45s прочитано: %s"
                  % (ЧЕЛОВЕЧЕСКИ.get(поле, поле), было, стало if стало else "— пусто —"))

    if прочитано.get("inn") and not инн_верен(прочитано["inn"]):
        print("  ИНН не проходит контрольный разряд — 1С такой не примет")
        расхождения.append(("inn", эталон.get("inn"), прочитано.get("inn")))
    if прочитано.get("snils") and not снилс_верен(прочитано["snils"]):
        print("  СНИЛС не проходит контрольный разряд — 1С такой не примет")
        расхождения.append(("snils", эталон.get("snils"), прочитано.get("snils")))

    return расхождения


def загрузить_эталон(имя):
    путь = os.path.join(ЭТАЛОН, имя + ".json")
    if not os.path.exists(путь):
        return None
    return json.load(io.open(путь, encoding="utf-8"))


def имя_по_файлу(путь):
    return os.path.splitext(os.path.basename(путь))[0]


# ─────────────────────────────────────────────────────────────────────

def main():
    p = argparse.ArgumentParser(
        description="Распознаёт синтетические сканы и сверяет реквизиты с эталоном.")
    p.add_argument("--комплект", help="имя одного комплекта, например 04_Дорохов_Сергей_Владимирович")
    p.add_argument("--сверить", metavar="ПУТЬ",
                   help="json с реквизитами (или папка с такими json) — сверить с эталоном, без OCR")
    p.add_argument("--вывод", metavar="КАТАЛОГ", help="куда сложить распознанное в json")
    args = p.parse_args()

    задания = []

    if args.сверить:
        цель = args.сверить
        файлы = []
        if os.path.isdir(цель):
            файлы = [os.path.join(цель, f) for f in sorted(os.listdir(цель)) if f.endswith(".json")]
        elif os.path.exists(цель):
            файлы = [цель]
        if not файлы:
            print("нечего сверять: %s" % цель)
            return 1
        for ф in файлы:
            данные = json.load(io.open(ф, encoding="utf-8"))
            задания.append((имя_по_файлу(ф), данные))
    else:
        if not os.path.isdir(КОМПЛЕКТЫ):
            print("нет папки комплекты/ — сначала сделайте сканы:")
            print("    python generate_scans.py --count 20")
            return 1
        имена = [args.комплект] if args.комплект else sorted(os.listdir(КОМПЛЕКТЫ))
        for имя in имена:
            папка = os.path.join(КОМПЛЕКТЫ, имя)
            if not os.path.isdir(папка):
                continue
            прочитано = распознать_комплект(папка)
            if прочитано is None:
                print("\nOCR недоступен: не установлены pytesseract и tesseract.")
                print("Либо поставьте их, либо отдайте на сверку то, что прочитала модель:")
                print("    python распознать.py --сверить ответ-агента.json")
                return 1
            задания.append((имя, прочитано))
            if args.вывод:
                os.makedirs(args.вывод, exist_ok=True)
                with io.open(os.path.join(args.вывод, имя + ".json"), "w", encoding="utf-8") as f:
                    json.dump(прочитано, f, ensure_ascii=False, indent=2)

    всего_расхождений = 0
    без_эталона = 0
    for имя, данные in задания:
        эталон = загрузить_эталон(имя)
        if эталон is None:
            print("\n%s\n  эталона нет — сверять не с чем" % имя)
            без_эталона += 1
            continue
        всего_расхождений += len(сверить(данные, эталон, имя))

    проверено = len(задания) - без_эталона
    print("\nитог: комплектов проверено %d, расхождений %d" % (проверено, всего_расхождений))
    return 0 if (всего_расхождений == 0 and проверено > 0) else 1


if __name__ == "__main__":
    sys.exit(main())
