# Наблюдатель за всем регламентом сразу: расчётный день, отчётный день, почта.
#
# Читает список из задания.json и по каждому заданию в свой срок просит
# агента выполнить один тик. Что сегодня за день и есть ли работа, решает
# не скрипт, а скилл задания: в обычный день тик заканчивается молча.
#
# Это «заводилка» для OpenCode, где таймеров внутри сессии нет. Для
# Claude Code она тоже годится — когда сессию держать открытой не хочется
# или мешает недельный срок жизни /loop:
#   .\следить.ps1                          # claude
#   .\следить.ps1 -Инструмент opencode
#   .\следить.ps1 -Инструмент opencode -Модель deepseek/deepseek-chat
#   .\следить.ps1 -Только почта            # одно задание из списка
#   .\следить.ps1 -Один                    # один проход по списку и выход
#   .\следить.ps1 -Показать                # что и как часто, без запуска агента
#
# В самой сессии Claude Code то же самое делает скилл zup-watch-start.
#
# Про разрешения — как в календарь\следить-за-календарем.ps1: запись в формы
# в настройках проекта стоит в «спрашивать», а в неинтерактивном запуске
# спросить некого, и тик отработал бы вхолостую. Поэтому на время прогона
# разрешаются ровно эти вызовы (--allowedTools у claude, --auto у opencode).
# Запреты из настроек и хуки при этом продолжают действовать.
#
# Останавливается по Ctrl+C. Живёт, пока открыт терминал. В планировщик
# задач его сознательно не ставят: задания заводят документы и готовят
# отчётность, им не место в работе без человека.

param(
    [ValidateSet('claude', 'opencode')]
    [string]$Инструмент = 'claude',

    [string]$Только = '',

    [string]$Модель = '',

    [switch]$Один,

    [switch]$Показать
)

$ErrorActionPreference = 'Stop'
$ПапкаРегламента = Split-Path -Parent $MyInvocation.MyCommand.Path
$КореньПроекта = Split-Path -Parent $ПапкаРегламента

$Список = Get-Content (Join-Path $ПапкаРегламента 'задания.json') -Raw -Encoding UTF8 | ConvertFrom-Json
$Задания = @($Список.'задания')
if ($Только) {
    $Задания = @($Задания | Where-Object { $_.'имя' -eq $Только })
    if ($Задания.Count -eq 0) {
        Write-Host "В задания.json нет задания «$Только»." -ForegroundColor Yellow
        exit 1
    }
}

function Команда {
    param($Задание)

    if ($Инструмент -eq 'claude') {
        $текст = "Выполни один тик по скиллу $($Задание.'скилл'). Делать нечего — ничего не делай и ничего не пиши."
        return @('claude', '-p', $текст, '--allowedTools', 'mcp__VA__execute_form_actions', 'mcp__VA__execute_feature_step')
    }
    $аргументы = @('opencode', 'run', '--auto', '--dir', $КореньПроекта, '--command', $Задание.'команда-opencode')
    if ($Модель) { $аргументы += @('-m', $Модель) }
    return $аргументы
}

if ($Показать) {
    Write-Host "Регламент ($Инструмент), проект $КореньПроекта" -ForegroundColor Cyan
    foreach ($з in $Задания) {
        $к = Команда $з
        Write-Host ("  {0,-16} каждые {1,6} с   {2}" -f $з.'имя', $з.'интервал-секунд', ($к -join ' '))
    }
    return
}

function Тик {
    param($Задание)

    $метка = Get-Date -Format 'HH:mm:ss'
    Write-Host "[$метка] $($Задание.'имя') ($Инструмент)" -ForegroundColor DarkGray
    $к = Команда $Задание
    Push-Location $КореньПроекта
    try {
        & $к[0] @($к[1..($к.Count - 1)])
    }
    catch {
        Write-Host "[$метка] тик не удался: $($_.Exception.Message)" -ForegroundColor Red
    }
    finally {
        Pop-Location
    }
}

if ($Один) {
    foreach ($з in $Задания) { Тик $з }
    return
}

# Тики идут по очереди, не внахлёст: два агента в одном клиенте тестирования
# мешают друг другу. Срок следующего тика считается от конца предыдущего.
$Срок = @{}
foreach ($з in $Задания) { $Срок[$з.'имя'] = Get-Date }

Write-Host "Слежу за регламентом: $($Задания.Count) зад., $Инструмент. Ctrl+C — остановить." -ForegroundColor Cyan
while ($true) {
    foreach ($з in $Задания) {
        if ((Get-Date) -ge $Срок[$з.'имя']) {
            Тик $з
            $Срок[$з.'имя'] = (Get-Date).AddSeconds([int]$з.'интервал-секунд')
        }
    }
    Start-Sleep -Seconds 15
}
