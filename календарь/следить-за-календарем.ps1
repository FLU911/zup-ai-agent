# Наблюдатель за календарём: расчётный день и отчётный день.
#
# Раз в сутки просит агента выполнить один тик каждого цикла:
#   расчёт      — сегодня день аванса или зарплаты? начислить и выплатить
#                 (регламент: календарь\ЦИКЛ-расчетный-день.md)
#   отчётность  — подошёл ли срок сдачи, было ли вчера кадровое событие
#                 (регламент: календарь\ЦИКЛ-отчетный-день.md)
#
# В обычный день оба тика заканчиваются молча и почти мгновенно.
#
# Работает с обоими инструментами — Claude Code и OpenCode:
#   .\следить-за-календарем.ps1                          # оба цикла, claude
#   .\следить-за-календарем.ps1 -Цикл расчет
#   .\следить-за-календарем.ps1 -Цикл отчетность -Инструмент opencode
#   .\следить-за-календарем.ps1 -Один                    # один прогон и выход
#   .\следить-за-календарем.ps1 -СпрашиватьВсегда        # без авторазрешения на запись
#
# ВАЖНО про разрешения. В настройках проекта execute_form_actions и
# execute_feature_step стоят в «спрашивать», а в неинтерактивном запуске
# спросить некого — такой вызов просто не проходит, и цикл честно
# отработает вхолостую: ничего не начислит и не пожалуется. Поэтому
# скрипт по умолчанию разрешает ровно эти два инструмента на время
# прогона (--allowedTools у claude, --auto у opencode). Запреты из
# .claude/settings.json и проверка exact_match при этом продолжают
# действовать. Не нужно — ключ -СпрашиватьВсегда, но тогда запускайте
# цикл руками и отвечайте на вопросы.
#
# Скрипт нужен прежде всего для OpenCode: в Claude Code постоянное
# наблюдение делается своей повторяющейся задачей и никакого внешнего
# запускателя не требует —
#   /loop 12h /zup-payday-watch
#   /loop 12h /zup-reporting-watch
#
# Останавливается по Ctrl+C. Живёт, пока открыт терминал. В планировщик
# задач его сознательно не ставят: циклы заводят документы и готовят
# отчётность, им не место в работе без человека.

param(
    [ValidateSet('оба', 'расчет', 'отчетность')]
    [string]$Цикл = 'оба',

    [ValidateSet('claude', 'opencode')]
    [string]$Инструмент = 'claude',

    [int]$Интервал = 0,

    [string]$Модель = '',

    [switch]$Один,

    [switch]$СпрашиватьВсегда
)

$ErrorActionPreference = 'Stop'
$ПапкаКалендаря = Split-Path -Parent $MyInvocation.MyCommand.Path
$КореньПроекта = Split-Path -Parent $ПапкаКалендаря

# ── настройки ────────────────────────────────────────────────────────
$ФайлНастроек = Join-Path $ПапкаКалендаря 'настройки.json'
if (-not (Test-Path $ФайлНастроек)) {
    Write-Host "Нет файла настройки.json." -ForegroundColor Yellow
    Write-Host "Скопируйте настройки.example.json в настройки.json и поправьте под свою базу."
    exit 1
}
$Настройки = Get-Content $ФайлНастроек -Raw -Encoding UTF8 | ConvertFrom-Json
if ($Интервал -le 0) {
    $Интервал = if ($Настройки.'интервал-проверки-секунд') { [int]$Настройки.'интервал-проверки-секунд' } else { 86400 }
}

$ЗаданиеРасчет = @"
Выполни один тик расчётного цикла строго по регламенту календарь/ЦИКЛ-расчетный-день.md.
Коротко: подключить клиент тестирования, взять дни выплат из календарь/настройки.json,
сверить их с настройками организаций в базе, посмотреть на сегодняшнюю дату.
Сегодня день аванса — начислить аванс и провести ведомости по всем организациям.
Сегодня день зарплаты — начислить зарплату, провести ведомости, резервы и отражения,
то есть закрыть месяц. День пропущен, а работа не сделана — догнать и пометить опоздание.
Месяцы раньше «не-раньше-месяца» из настроек не трогать вообще.
Обновить календарь/состояние.json и календарь/журнал.md.
Сегодня обычный день и догонять нечего — ничего не делать и ничего не писать.
"@

$ЗаданиеОтчетность = @"
Выполни один тик отчётного цикла строго по регламенту календарь/ЦИКЛ-отчетный-день.md.
Коротко: подключить клиент тестирования, посмотреть вчерашние приёмы и увольнения
(по ним срок ЕФС-1 подраздел 1.1 — сегодня, но подавать только с согласия человека),
затем сверить сегодняшнюю дату со сроками из календарь/КАЛЕНДАРЬ-отчетности.md.
Срок подошёл и месяцы периода закрыты — сформировать отчёты по всем организациям,
проверить контрольные соотношения и выгрузку, доложить человеку, ЧТО и ДО КАКОГО ЧИСЛА
ему нужно отправить. Отчёты никуда не отправлять. Обновить календарь/состояние.json
и календарь/журнал.md.
Ни сроков, ни вчерашних кадровых событий нет — ничего не делать и ничего не писать.
"@

function Тик {
    param([string]$Имя, [string]$Задание)

    $метка = Get-Date -Format 'HH:mm:ss'
    Write-Host "[$метка] $Имя ($Инструмент)" -ForegroundColor DarkGray
    Push-Location $КореньПроекта
    try {
        if ($Инструмент -eq 'claude') {
            if ($СпрашиватьВсегда) {
                & claude -p $Задание
            }
            else {
                & claude -p $Задание --allowedTools 'mcp__VA__execute_form_actions' 'mcp__VA__execute_feature_step'
            }
        }
        else {
            $аргументы = @('run', '--auto', '--dir', $КореньПроекта)
            if ($Модель) { $аргументы += @('-m', $Модель) }
            $аргументы += $Задание
            & opencode @аргументы
        }
    }
    catch {
        Write-Host "[$метка] тик не удался: $($_.Exception.Message)" -ForegroundColor Red
    }
    finally {
        Pop-Location
    }
}

function Прогон {
    if ($Цикл -eq 'оба' -or $Цикл -eq 'расчет') {
        Тик -Имя 'расчётный день' -Задание $ЗаданиеРасчет
    }
    if ($Цикл -eq 'оба' -or $Цикл -eq 'отчетность') {
        Тик -Имя 'отчётный день' -Задание $ЗаданиеОтчетность
    }
}

if ($Один) {
    Прогон
    return
}

$часы = [math]::Round($Интервал / 3600, 1)
Write-Host "Слежу за календарём: $Цикл, $Инструмент, каждые $часы ч. Ctrl+C — остановить." -ForegroundColor Cyan
while ($true) {
    Прогон
    Start-Sleep -Seconds $Интервал
}
