#!/usr/bin/env bash
# Наблюдатель за календарём (вариант для bash): расчётный день и отчётный день.
#
# Раз в сутки просит агента выполнить один тик каждого цикла. В обычный
# день оба тика заканчиваются молча. Работает и с Claude Code, и с OpenCode:
#
#   ./следить-за-календарем.sh                        # оба цикла, claude
#   ./следить-за-календарем.sh расчет                 # только расчёт
#   ./следить-за-календарем.sh отчетность opencode    # только отчётность
#   ./следить-за-календарем.sh оба claude 43200       # свой интервал, секунды
#   ODIN_PROGON=1 ./следить-за-календарем.sh          # один прогон и выход
#   SPRASHIVAT=1 ./следить-за-календарем.sh           # без авторазрешения на запись
#
# ВАЖНО про разрешения. В настройках проекта execute_form_actions и
# execute_feature_step стоят в «спрашивать», а в неинтерактивном запуске
# спросить некого — такой вызов просто не проходит, и цикл честно
# отработает вхолостую: ничего не начислит и не пожалуется. Поэтому
# скрипт по умолчанию разрешает ровно эти два инструмента на время
# прогона. Запреты из .claude/settings.json и проверка exact_match при
# этом продолжают действовать. Не нужно — SPRASHIVAT=1, но тогда
# запускайте цикл руками и отвечайте на вопросы.
#
# Скрипт нужен прежде всего для OpenCode: в Claude Code постоянное
# наблюдение делается своей повторяющейся задачей и никакого внешнего
# запускателя не требует —
#   /loop 12h /zup-payday-watch
#   /loop 12h /zup-reporting-watch
#
# Останавливается по Ctrl+C. Живёт, пока открыт терминал. В cron его
# сознательно не ставят: циклы заводят документы и готовят отчётность,
# им не место в работе без человека.
#
# Имена переменных латиницей не по вкусу, а по необходимости: bash
# разрешает в именах только латиницу, цифры и подчёркивание. Кириллическое
# имя переменной он разбирает как попытку запустить команду.

set -u

CYCLE="${1:-оба}"
TOOL="${2:-claude}"
CAL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$CAL_DIR")"
SETTINGS="$CAL_DIR/настройки.json"

case "$CYCLE" in
    оба|расчет|отчетность) ;;
    *) echo "Первый аргумент: оба, расчет или отчетность (было: $CYCLE)"; exit 1 ;;
esac

case "$TOOL" in
    claude|opencode) ;;
    *) echo "Второй аргумент: claude или opencode (было: $TOOL)"; exit 1 ;;
esac

if [ ! -f "$SETTINGS" ]; then
    echo "Нет файла настройки.json."
    echo "Скопируйте настройки.example.json в настройки.json и поправьте под свою базу."
    exit 1
fi

INTERVAL="${3:-}"
if [ -z "$INTERVAL" ]; then
    INTERVAL=$(python -c "import json,io;print(json.load(io.open(r'$SETTINGS',encoding='utf-8')).get('интервал-проверки-секунд',86400))" 2>/dev/null || echo 86400)
fi

TASK_PAYROLL="Выполни один тик расчётного цикла строго по регламенту календарь/ЦИКЛ-расчетный-день.md.
Коротко: подключить клиент тестирования, взять дни выплат из календарь/настройки.json,
сверить их с настройками организаций в базе, посмотреть на сегодняшнюю дату.
Сегодня день аванса — начислить аванс и провести ведомости по всем организациям.
Сегодня день зарплаты — начислить зарплату, провести ведомости, резервы и отражения,
то есть закрыть месяц. День пропущен, а работа не сделана — догнать и пометить опоздание.
Месяцы раньше «не-раньше-месяца» из настроек не трогать вообще.
Обновить календарь/состояние.json и календарь/журнал.md.
Сегодня обычный день и догонять нечего — ничего не делать и ничего не писать."

TASK_REPORTS="Выполни один тик отчётного цикла строго по регламенту календарь/ЦИКЛ-отчетный-день.md.
Коротко: подключить клиент тестирования, посмотреть вчерашние приёмы и увольнения
(по ним срок ЕФС-1 подраздел 1.1 — сегодня, но подавать только с согласия человека),
затем сверить сегодняшнюю дату со сроками из календарь/КАЛЕНДАРЬ-отчетности.md.
Срок подошёл и месяцы периода закрыты — сформировать отчёты по всем организациям,
проверить контрольные соотношения и выгрузку, доложить человеку, ЧТО и ДО КАКОГО ЧИСЛА
ему нужно отправить. Отчёты никуда не отправлять. Обновить календарь/состояние.json
и календарь/журнал.md.
Ни сроков, ни вчерашних кадровых событий нет — ничего не делать и ничего не писать."

tick() {
    local name="$1"
    local task="$2"
    echo "[$(date +%H:%M:%S)] $name ($TOOL)"
    cd "$PROJECT_ROOT" || return 1
    if [ "$TOOL" = "claude" ]; then
        if [ "${SPRASHIVAT:-}" = "1" ]; then
            claude -p "$task" || echo "тик не удался"
        else
            claude -p "$task" --allowedTools mcp__VA__execute_form_actions mcp__VA__execute_feature_step || echo "тик не удался"
        fi
    else
        opencode run --auto --dir "$PROJECT_ROOT" "$task" || echo "тик не удался"
    fi
}

run_once() {
    if [ "$CYCLE" = "оба" ] || [ "$CYCLE" = "расчет" ]; then
        tick "расчётный день" "$TASK_PAYROLL"
    fi
    if [ "$CYCLE" = "оба" ] || [ "$CYCLE" = "отчетность" ]; then
        tick "отчётный день" "$TASK_REPORTS"
    fi
}

if [ "${ODIN_PROGON:-}" = "1" ]; then
    run_once
    exit 0
fi

echo "Слежу за календарём: $CYCLE, $TOOL, каждые $INTERVAL с. Ctrl+C — остановить."
while true; do
    run_once
    sleep "$INTERVAL"
done
