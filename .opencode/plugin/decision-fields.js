// Плагин OpenCode: останавливает агента на полях-решениях.
//
// Это ЗЕРКАЛО хука Claude Code .claude/hooks/check_decision_fields.py.
// Правишь одно — правь второе. После правки прогони сверку:
//   python drafts/инструменты/сверить-хуки.py
//
// Есть поля, где ввод значения — не ввод данных, а РЕШЕНИЕ: основание
// увольнения и статья ТК. Повод завести: 30.08.2026
// агент оформил увольнение по письму и сам выбрал основание, п. 3 ч. 1
// ст. 77, которого в задании не было. Правило «не решай за человека»
// в скиллах было — не удержало.
//
// ВАЖНОЕ ОТЛИЧИЕ от exact-match.js. Тот запрещает вызов: там формальная
// ошибка, которая чинится добавлением параметра. Здесь решение может
// быть верным — его должен подтвердить человек. В OpenCode плагин умеет
// только пропустить или бросить ошибку, промежуточного «спросить» у него
// нет. Поэтому бросаем — с текстом, который объясняет, что делать:
// названо в задании — повтори вызов, решил сам — остановись и спроси.

// Список намеренно короткий: только юридическая квалификация. Рутину
// (организация, месяц, сумма) сюда не добавлять — иначе человек начнёт
// жать «да» не глядя, и хук перестанет работать вовсе.
const РЕШЕНИЯ = {
  ОснованиеУвольнения:
    "основание увольнения — юридическая квалификация, а не данные",
  СтатьяТКРФ: "статья ТК — юридическая квалификация, а не данные",
}

const ХВОСТ = [
  "Значение в таком поле — это решение человека, а не данные задачи.",
  "Названо в задании — подтверди и повтори вызов. Выбрал сам — остановись",
  "и спроси: 30.08.2026 агент так же молча выбрал основание увольнения,",
  "которого в задании не было.",
  "В неинтерактивном запуске запиши «нужно-согласие» и доложи человеку.",
].join("\n")

function решения(имяИнструмента, аргументы) {
  const найдено = []
  if (!аргументы || typeof аргументы !== "object") return найдено

  const проверить = (имя) => {
    if (имя && Object.prototype.hasOwnProperty.call(РЕШЕНИЯ, имя)) {
      найдено.push(`${имя} — ${РЕШЕНИЯ[имя]}`)
    }
  }

  if (имяИнструмента.endsWith("manage_form_elements")) {
    проверить(аргументы.element_name)
    return найдено
  }

  if (имяИнструмента.endsWith("execute_form_actions")) {
    const сырое = аргументы.actions_json ?? "[]"
    let действия
    try {
      действия = typeof сырое === "string" ? JSON.parse(сырое) : сырое
    } catch {
      return найдено // не наше дело — пусть падает штатно
    }
    if (!Array.isArray(действия)) return найдено
    for (const д of действия) {
      if (д && typeof д === "object") проверить(д.element_name)
    }
  }

  return найдено
}

export const DecisionFields = async () => ({
  "tool.execute.before": async (input, output) => {
    const найдено = решения(input.tool || "", output.args)
    if (найдено.length === 0) return
    throw new Error(`Поле-решение: ${найдено.join("; ")}.\n${ХВОСТ}`)
  },
})
