// Правишь одно — правь второе.
//
// Шесть значений задаёт человек, а не агент: организация, подразделение,
// дата утверждения, должность, оклад и количество ставок. Позиция —
// основание для приёма на работу, и неверный оклад или подразделение
// разойдутся дальше по всем, кого на неё примут.
//
// Проверка одна и в конце — на кнопке сохранения. Спрашивать на каждом
// из шести полей нельзя: человек начнёт жать «да» не глядя.
//
// Одно требование — несколько допустимых имён: у документа «Изменение
// штатного расписания» организация лежит в `Организация`, а на форме
// самой позиции она же называется `Владелец`; дата — `ДатаВступленияВСилу`
// у документа и `ДатаУтверждения` у позиции.
//
// Имена сверены со словарями drafts/словари/ШтатноеРасписание.feature
// и ИзменениеШтатногоРасписания.feature.
//
// ОТЛИЧИЕ ОТ CLAUDE CODE: там решение «ask» — человек подтверждает.
// В OpenCode промежуточного «спросить» нет, поэтому бросаем ошибку
// с текстом, который объясняет, что делать дальше.

import fs from "node:fs"
import os from "node:os"
import path from "node:path"

// Вопрос человеку → имена элементов, любое из которых его закрывает.
const ОБЯЗАТЕЛЬНЫЕ = [
  ["в какой организации", ["Организация", "Владелец"]],
  ["в каком подразделении", ["Подразделение"]],
  ["с какой даты утверждена", ["ДатаУтверждения", "ДатаВступленияВСилу"]],
  ["на какую должность", ["Должность"]],
  ["какой оклад", ["Оклад"]],
  ["сколько ставок", ["КоличествоСтавок"]],
]

// Поля, которые есть только у штатного расписания.
const МАРКЕРЫ = new Set(["ДатаУтверждения", "Оклад", "ДатаВступленияВСилу"])

const КНОПКИ_СОХРАНЕНИЯ = new Set([
  "КомандаОК",
  "ФормаПровести",
  "ФормаПровестиИЗакрыть",
  "КомандаПровести",
  "КомандаПровестиИЗакрыть",
])

const КНОПКИ_ЗАКРЫТИЯ = new Set([
  "ФормаЗакрыть",
  "КомандаЗакрыть",
  "ФормаОтменаПроведения",
])

const ВВОД = new Set(["set_value", "input_text"])

const СОСТОЯНИЕ = path.join(os.tmpdir(), "zup-agent-shr.json")
const ЖИВЁТ = 2 * 60 * 60 * 1000

const ВСЕ_ИМЕНА = new Set(ОБЯЗАТЕЛЬНЫЕ.flatMap(([, имена]) => имена))

const ХВОСТ = [
  "Позиция — основание для приёма на работу: неверный оклад или",
  "подразделение разойдутся дальше по всем, кого на неё примут.",
  "Названо в задании — заполни и повтори сохранение. Не названо —",
  "остановись и спроси человека, не подставляй по смыслу.",
  "В неинтерактивном запуске запиши «нужно-согласие» и доложи человеку.",
].join("\n")

function прочитать() {
  try {
    const s = JSON.parse(fs.readFileSync(СОСТОЯНИЕ, "utf8"))
    if (!s || typeof s !== "object") return null
    if (Date.now() - (s.начато || 0) > ЖИВЁТ) return null
    return s
  } catch {
    return null
  }
}

function записать(s) {
  try {
    fs.writeFileSync(СОСТОЯНИЕ, JSON.stringify(s), "utf8")
  } catch {
    // не смогли — не мешаем работать
  }
}

function забыть() {
  try {
    fs.unlinkSync(СОСТОЯНИЕ)
  } catch {
    // уже нет — и хорошо
  }
}

function действия(имяИнструмента, аргументы) {
  const out = []
  if (!аргументы || typeof аргументы !== "object") return out

  if (имяИнструмента.endsWith("manage_form_elements")) {
    out.push([аргументы.action || "", аргументы.element_name || ""])
    return out
  }

  if (имяИнструмента.endsWith("execute_form_actions")) {
    const сырое = аргументы.actions_json ?? "[]"
    let список
    try {
      список = typeof сырое === "string" ? JSON.parse(сырое) : сырое
    } catch {
      return out // не наше дело — пусть падает штатно
    }
    if (!Array.isArray(список)) return out
    for (const д of список) {
      if (д && typeof д === "object") out.push([д.action || "", д.element_name || ""])
    }
  }

  return out
}

function чегоНет(заполнено) {
  const есть = new Set(заполнено)
  return ОБЯЗАТЕЛЬНЫЕ.filter(([, имена]) => !имена.some((и) => есть.has(и)))
}

export const StaffingFields = async () => ({
  "tool.execute.before": async (input, output) => {
    const пары = действия(input.tool || "", output.args)
    if (пары.length === 0) return

    const состояние = прочитать() || { начато: Date.now(), заполнено: [], штатное: false }

    // 1. Копим заполненные поля с самого начала.
    let изменилось = false
    for (const [действие, имя] of пары) {
      if (!ВВОД.has(действие)) continue
      if (ВСЕ_ИМЕНА.has(имя) && !состояние.заполнено.includes(имя)) {
        состояние.заполнено.push(имя)
        изменилось = true
      }
      if (МАРКЕРЫ.has(имя) && !состояние.штатное) {
        состояние.штатное = true
        изменилось = true
      }
    }
    if (изменилось) записать(состояние)

    // 2. Проверяем на сохранении.
    const сохраняют = пары.some(
      ([действие, имя]) => действие === "click_button" && КНОПКИ_СОХРАНЕНИЯ.has(имя),
    )
    const закрывают = пары.some(
      ([действие, имя]) => действие === "click_button" && КНОПКИ_ЗАКРЫТИЯ.has(имя),
    )
    if (закрывают && !сохраняют) {
      забыть()
      return
    }
    if (!сохраняют) return

    const штатное = состояние.штатное
    const нет = чегоНет(состояние.заполнено)
    забыть() // спрашиваем один раз, иначе зациклимся
    if (!штатное || нет.length === 0) return

    const перечень = нет
      .map(([вопрос, имена]) => `  - ${вопрос} (${имена.join(" / ")})`)
      .join("\n")
    throw new Error(
      `Позиция штатного расписания: не заполнено то, что задаёт человек.\n${перечень}\n${ХВОСТ}`,
    )
  },
})
