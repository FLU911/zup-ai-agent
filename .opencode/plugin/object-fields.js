// Плагин OpenCode: не даёт записать объект, у которого не заполнено главное.
//
// Это ЗЕРКАЛО хука Claude Code .claude/hooks/check_object_fields.py.
// Правишь одно — правь второе.
//
// Общий предохранитель на создание любого объекта в базе. Частные
// проверки (приём на работу, штатное расписание) живут отдельно, этот —
// про то, без чего запись бессмысленна у всех:
//
//   документ    — организация, дата документа и тот, по кому документ;
//   справочник  — наименование.
//
// Какой объект открыт, видно только из навигационной ссылки
// `e1cib/list/Документ.Отпуск`: у инструментов формы параметра объекта
// нет, они работают с активным окном. По имени объекта в таблице
// .claude/hooks/требования-объектов.json находим, что требовать; таблицу
// собирает drafts/инструменты/собрать-требования-объектов.py из словарей
// действий, имена там настоящие. Объект не опознан — работает общее
// правило: проводят документ — спроси про организацию, записывают
// элемент — про наименование или организацию.
//
// Проверка одна и в конце, на кнопке записи: спрашивать на каждом поле
// нельзя, человек начнёт жать «да» не глядя.
//
// Требование закрывает и ввод значения, и чтение поля через
// `get_form_element_data`: организация и дата часто подставляются формой
// по умолчанию, и правило 4a CLAUDE.md всё равно велит проверить, что
// в поле стоит нужное.
//
// ОТЛИЧИЕ ОТ CLAUDE CODE: там решение «ask» — человек подтверждает.
// В OpenCode промежуточного «спросить» нет, поэтому бросаем ошибку
// с текстом, который объясняет, что делать дальше.

import fs from "node:fs"
import os from "node:os"
import path from "node:path"
import { fileURLToPath } from "node:url"

const ЗДЕСЬ = path.dirname(fileURLToPath(import.meta.url))
const ТАБЛИЦА = path.join(ЗДЕСЬ, "..", "..", ".claude", "hooks",
  "требования-объектов.json")

// Из навигационной ссылки: e1cib/list/Документ.Отпуск,
// e1cib/data/Справочник.Должности.Форма.ФормаЭлемента
const ССЫЛКА =
  /(Документ|Справочник|ПланВидовРасчета|РегистрСведений|Обработка|Отчет)\.([A-Za-zА-Яа-яЁё0-9_]+)/

// Действия, после которых в поле появляется значение.
const ВВОД = new Set(["set_value", "input_text", "select_from_dropdown",
  "set_checkbox", "set_radio_button", "open_choice_form"])

// Кнопки, на которых объект попадает в базу.
const КНОПКИ_ПРОВЕДЕНИЯ = new Set(["ФормаПровести", "ФормаПровестиИЗакрыть",
  "КомандаПровести", "КомандаПровестиИЗакрыть"])
const КНОПКИ_ЗАПИСИ = new Set(["ФормаЗаписать", "ФормаЗаписатьИЗакрыть",
  "КомандаЗаписать", "КомандаЗаписатьИЗакрыть", "КомандаОК"])

// Начали новый объект — накопленное больше не про него.
const КНОПКИ_СОЗДАНИЯ = new Set(["ФормаСоздать", "КомандаСоздать",
  "ФормаСкопировать"])
const КНОПКИ_ЗАКРЫТИЯ = new Set(["ФормаЗакрыть", "КомандаЗакрыть",
  "ФормаОтменаПроведения"])

// Общее правило для неопознанного объекта.
const ФОЛБЭК_ДОКУМЕНТ = [["в какой организации",
  ["Организация", "ОрганизацияПлательщик", "Владелец"]]]
const ФОЛБЭК_ЗАПИСЬ = [["наименование или организация",
  ["Наименование", "ФИО", "НаименованиеПолное", "Организация", "Владелец"]]]

const СОСТОЯНИЕ = path.join(os.tmpdir(), "zup-agent-object.json")
const ЖИВЁТ = 2 * 60 * 60 * 1000

const ХВОСТ = [
  "Эти значения берутся из задания, а не подбираются агентом.",
  "Названы в задании — заполни и повтори. Не названы — остановись",
  "и спроси человека, не подставляй по смыслу: организация и дата",
  "документа определяют, в чей учёт и в какой месяц он ляжет,",
  "а видно это станет только на сверке.",
  "Если поле уже заполнено формой по умолчанию — прочитай его через",
  "get_form_element_data, убедись, что там нужное значение, и повтори",
  "запись: прочитанное поле проверка считает закрытым.",
  "В неинтерактивном запуске запиши «нужно-согласие» и доложи человеку.",
].join("\n")

function требованияОбъектов() {
  try {
    const t = JSON.parse(fs.readFileSync(ТАБЛИЦА, "utf8"))
    return (t && t["объекты"]) || {}
  } catch {
    return {} // нет таблицы — останется общее правило
  }
}

function прочитатьСостояние() {
  try {
    const s = JSON.parse(fs.readFileSync(СОСТОЯНИЕ, "utf8"))
    if (!s || typeof s !== "object") return null
    if (Date.now() - (s["начато"] || 0) > ЖИВЁТ) return null
    return s
  } catch {
    return null
  }
}

function записать(s) {
  try {
    fs.writeFileSync(СОСТОЯНИЕ, JSON.stringify(s), "utf8")
  } catch {
    // не смогли — не мешаем работать
  }
}

function забыть() {
  try {
    fs.unlinkSync(СОСТОЯНИЕ)
  } catch {
    // уже нет — и хорошо
  }
}

// «спрошено» — вопрос по этому объекту уже задавали. Второе нажатие той
// же кнопки пропускаем, иначе после ответа приходит тот же вопрос ещё раз.
function чистое(объект = null, спрошено = false) {
  return {
    "начато": Date.now(),
    "объект": объект,
    "заполнено": [],
    "проверено": [],
    "спрошено": спрошено,
  }
}

function действия(имяИнструмента, аргументы) {
  const out = []
  if (!аргументы || typeof аргументы !== "object") return out

  if (имяИнструмента.endsWith("manage_form_elements")) {
    out.push([аргументы.action || "", аргументы.element_name || "",
      аргументы.table_name || ""])
    return out
  }

  if (имяИнструмента.endsWith("execute_form_actions")) {
    const сырое = аргументы.actions_json ?? "[]"
    let список
    try {
      список = typeof сырое === "string" ? JSON.parse(сырое) : сырое
    } catch {
      return out // не наше дело — пусть падает штатно
    }
    if (!Array.isArray(список)) return out
    for (const д of список) {
      if (д && typeof д === "object") {
        out.push([д.action || "", д.element_name || "", д.table_name || ""])
      }
    }
  }

  return out
}

function чегоНет(требуется, закрыто) {
  const есть = new Set(закрыто)
  return требуется.filter(([, имена]) => !имена.some((и) => есть.has(и)))
}

function причина(объект, нет, документ) {
  const перечень = нет
    .map(([вопрос, имена]) => `  - ${вопрос} (${имена.join(" / ")})`)
    .join("\n")
  const что = объект
    ? `«${объект.split(".").pop()}»`
    : документ ? "Документ" : "Элемент справочника"
  const действие = документ ? "проведением" : "записью"
  return `${что}: перед ${действие} не заполнено главное.\n${перечень}\n${ХВОСТ}`
}

export const ObjectFields = async () => ({
  "tool.execute.before": async (input, output) => {
    const имяИнструмента = input.tool || ""
    const аргументы = output.args || {}
    const состояние = прочитатьСостояние() || чистое()

    // 1. Навигационная ссылка — единственное место, где виден объект.
    if (имяИнструмента.endsWith("window_management")) {
      const действие = аргументы.action || ""
      if (действие === "open_navigation") {
        const m = ССЫЛКА.exec(аргументы.navigation_link || "")
        if (m) записать(чистое(`${m[1]}.${m[2]}`))
      } else if (действие === "close") {
        забыть()
      }
      return
    }

    // 2. Прочитанное поле закрывает требование не хуже введённого.
    if (имяИнструмента.endsWith("get_form_element_data")) {
      const имя = аргументы.element_name || ""
      if (имя && !состояние["проверено"].includes(имя)) {
        состояние["проверено"].push(имя)
        записать(состояние)
      }
      return
    }

    const пары = действия(имяИнструмента, аргументы)
    if (пары.length === 0) return

    // 3. Копим заполненные поля шапки. Копим всегда: объект мог быть
    //    опознан раньше, а мог не опознаться вовсе.
    let изменилось = false
    for (const [действие, имя, имяТаблицы] of пары) {
      if (имяТаблицы || !имя) continue // поле таблицы обязательным не бывает
      if (ВВОД.has(действие) && !состояние["заполнено"].includes(имя)) {
        состояние["заполнено"].push(имя)
        изменилось = true
      }
    }

    const создают = пары.some(([действие, имя]) =>
      действие === "create_new" ||
      (действие === "click_button" && КНОПКИ_СОЗДАНИЯ.has(имя)))
    const пишут = пары
      .filter(([действие, имя]) => действие === "click_button" &&
        (КНОПКИ_ПРОВЕДЕНИЯ.has(имя) || КНОПКИ_ЗАПИСИ.has(имя)))
      .map(([, имя]) => имя)
    const закрывают = пары.some(([действие, имя]) =>
      действие === "click_button" && КНОПКИ_ЗАКРЫТИЯ.has(имя))

    if (пишут.length === 0) {
      if (создают || закрывают) {
        // Новая карточка или уход с формы: объект помним, поля забываем.
        записать(чистое(состояние["объект"]))
      } else if (изменилось) {
        записать(состояние)
      }
      return
    }

    // 4. Проверяем на записи.
    const объект = состояние["объект"]
    if (состояние["спрошено"]) {
      записать(чистое(объект))
      return
    }

    const закрыто = состояние["заполнено"].concat(состояние["проверено"])
    const документ = пишут.some((имя) => КНОПКИ_ПРОВЕДЕНИЯ.has(имя))

    let правила = null
    const запись = требованияОбъектов()[объект || ""]
    if (запись && запись["требуется"]) {
      правила = запись["требуется"]
    } else if (объект) {
      // Объект опознан, но в таблице его нет: своя проверка, отчёт,
      // обработка. Молчим, чтобы не спрашивать дважды.
      записать(чистое(объект))
      return
    } else {
      правила = документ ? ФОЛБЭК_ДОКУМЕНТ : ФОЛБЭК_ЗАПИСЬ
    }

    const нет = чегоНет(правила, закрыто)
    записать(чистое(объект, нет.length > 0))
    if (нет.length === 0) return

    throw new Error(причина(объект, нет, документ))
  },
})
