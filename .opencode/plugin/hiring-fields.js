// Плагин OpenCode: не даёт провести приём на работу, пока не заполнено главное.
//
// Это ЗЕРКАЛО хука Claude Code .claude/hooks/check_hiring_fields.py.
// Правишь одно — правь второе.
//
// На приёме шесть значений задаёт человек, а не агент: кого, кем, куда,
// в какую организацию, по какому графику и с какого числа. Пропущенное
// поле стоит дорого: часть из них после проведения меняется только
// исправлением документа, а график тянет за собой табель и расчёт.
//
// Проверка одна и в конце — на кнопке проведения. Спрашивать на каждом
// из шести полей нельзя: человек начнёт жать «да» не глядя, и хуки
// перестанут работать вовсе.
//
// Тип документа по одному вызову не виден — у инструмента нет параметра
// формы. Поэтому плагин копит заполненные поля ВСЕГДА, а признаком приёма
// считает ввод в `ДатаПриема`: это поле есть только здесь. Копить надо
// с самого начала: агент обычно вводит организацию и сотрудника раньше
// даты приёма. Накопленное живёт до первого проведения или закрытия
// формы. Если `ДатаПриема` не трогали вовсе, проверки не будет — но этот
// случай ловит сама 1С, дата приёма обязательна для проведения.
//
// ОТЛИЧИЕ ОТ CLAUDE CODE: там решение «ask» — человек подтверждает.
// В OpenCode промежуточного «спросить» нет, поэтому бросаем ошибку
// с текстом, который объясняет, что делать дальше.

import fs from "node:fs"
import os from "node:os"
import path from "node:path"

// Имена сверены со словарём drafts/словари/ПриемНаРаботу.feature.
const ОБЯЗАТЕЛЬНЫЕ = {
  Сотрудник: "кого принимаем (ФИО)",
  Должность: "на какую должность",
  Подразделение: "в какое подразделение",
  Организация: "в какую организацию",
  График: "по какому графику работы",
  ДатаПриема: "с какого числа принять",
}

const МАРКЕР = "ДатаПриема"
const ПОЗИЦИЯ = "ПозицияШтатногоРасписания"
const ЗАКРЫВАЕТ = ["Должность", "Подразделение"]

const КНОПКИ_ПРОВЕДЕНИЯ = new Set([
  "ФормаПровести",
  "ФормаПровестиИЗакрыть",
  "КомандаПровести",
  "КомандаПровестиИЗакрыть",
])

// Ушли с формы, ничего не проведя — накопленное больше не про этот документ.
const КНОПКИ_ЗАКРЫТИЯ = new Set([
  "ФормаЗакрыть",
  "КомандаЗакрыть",
  "ФормаОтменаПроведения",
])

const ВВОД = new Set(["set_value", "input_text"])

const СОСТОЯНИЕ = path.join(os.tmpdir(), "zup-agent-priem.json")
const ЖИВЁТ = 2 * 60 * 60 * 1000

const ХВОСТ = [
  "Эти шесть значений берутся из задания, а не подбираются агентом.",
  "Названы в задании — заполни и повтори проведение. Их там нет —",
  "остановись и спроси человека, не угадывай: график тянет за собой",
  "табель и расчёт, а подразделение и должность после проведения",
  "правятся только исправлением документа.",
  "В неинтерактивном запуске запиши «нужно-согласие» и доложи человеку.",
].join("\n")

function прочитать() {
  try {
    const s = JSON.parse(fs.readFileSync(СОСТОЯНИЕ, "utf8"))
    if (!s || typeof s !== "object") return null
    if (Date.now() - (s.взведён || 0) > ЖИВЁТ) return null
    return s
  } catch {
    return null
  }
}

function записать(s) {
  try {
    fs.writeFileSync(СОСТОЯНИЕ, JSON.stringify(s), "utf8")
  } catch {
    // не смогли — не мешаем работать
  }
}

function забыть() {
  try {
    fs.unlinkSync(СОСТОЯНИЕ)
  } catch {
    // уже нет — и хорошо
  }
}

function действия(имяИнструмента, аргументы) {
  const out = []
  if (!аргументы || typeof аргументы !== "object") return out

  if (имяИнструмента.endsWith("manage_form_elements")) {
    out.push([аргументы.action || "", аргументы.element_name || ""])
    return out
  }

  if (имяИнструмента.endsWith("execute_form_actions")) {
    const сырое = аргументы.actions_json ?? "[]"
    let список
    try {
      список = typeof сырое === "string" ? JSON.parse(сырое) : сырое
    } catch {
      return out // не наше дело — пусть падает штатно
    }
    if (!Array.isArray(список)) return out
    for (const д of список) {
      if (д && typeof д === "object") out.push([д.action || "", д.element_name || ""])
    }
  }

  return out
}

function чегоНет(заполнено) {
  const есть = new Set(заполнено)
  if (есть.has(ПОЗИЦИЯ)) for (const и of ЗАКРЫВАЕТ) есть.add(и)
  return Object.entries(ОБЯЗАТЕЛЬНЫЕ).filter(([имя]) => !есть.has(имя))
}

export const HiringFields = async () => ({
  "tool.execute.before": async (input, output) => {
    const пары = действия(input.tool || "", output.args)
    if (пары.length === 0) return

    const состояние = прочитать() || { взведён: Date.now(), заполнено: [], приём: false }

    // 1. Копим заполненные поля — с самого начала, а не с опознания приёма.
    let изменилось = false
    for (const [действие, имя] of пары) {
      if (!ВВОД.has(действие)) continue
      if (имя in ОБЯЗАТЕЛЬНЫЕ || имя === ПОЗИЦИЯ) {
        if (!состояние.заполнено.includes(имя)) {
          состояние.заполнено.push(имя)
          изменилось = true
        }
      }
      if (имя === МАРКЕР && !состояние.приём) {
        состояние.приём = true
        изменилось = true
      }
    }
    if (изменилось) записать(состояние)

    // 2. Проверяем на проведении.
    const жмут = пары.some(
      ([действие, имя]) => действие === "click_button" && КНОПКИ_ПРОВЕДЕНИЯ.has(имя),
    )
    const закрывают = пары.some(
      ([действие, имя]) => действие === "click_button" && КНОПКИ_ЗАКРЫТИЯ.has(имя),
    )
    if (закрывают && !жмут) {
      забыть() // ушли с формы — накопленное больше не про этот документ
      return
    }
    if (!жмут) return

    const приём = состояние.приём
    const нет = чегоНет(состояние.заполнено)
    // Провели что-то — следующий документ начинаем с чистого листа.
    забыть()
    if (!приём || нет.length === 0) return

    const перечень = нет.map(([имя, вопрос]) => `  - ${вопрос} (${имя})`).join("\n")
    throw new Error(
      `Приём на работу: не заполнено то, что задаёт человек.\n${перечень}\n${ХВОСТ}`,
    )
  },
})
