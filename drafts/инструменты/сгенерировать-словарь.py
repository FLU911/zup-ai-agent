# -*- coding: utf-8 -*-
"""
Генератор словаря действий из исходников конфигурации.

Словарь — это перечень того, что можно сделать с объектом: закладки,
поля шапки, флаги, переключатели, команды, таблицы с колонками и их
командами. Имена берутся из выгрузки конфигурации в XML, поэтому они
настоящие — в отличие от имён, подобранных по смыслу.

Чего генератор НЕ знает: видимость и доступность элемента в конкретный
момент. Половина элементов скрыта функциональными опциями и состоянием
документа, и увидеть это можно только на живой форме. Поэтому на выходе
всегда стоит `@черновик`, и снимает его человек или агент после прогона.

Запуск:

    python сгенерировать-словарь.py --вид Documents --имя Премия
    python сгенерировать-словарь.py --вид Catalogs --имя Должности
    python сгенерировать-словарь.py --вид ChartsOfCalculationTypes --имя Начисления
    python сгенерировать-словарь.py --список файл-со-списком.txt

По умолчанию исходники ищутся в `исходники-конфигурации/`, результат
кладётся в `drafts/словари/`.
"""

import argparse
import io
import os
import re
import sys
import xml.etree.ElementTree as ET

ВИДЫ = {
    "Documents": ("Документ", ["ФормаДокумента", "ДокументФорма", "ФормаЭлемента"]),
    "Catalogs": ("Справочник", ["ФормаЭлемента", "ЭлементФорма", "ФормаСписка"]),
    "ChartsOfCalculationTypes": ("ПланВидовРасчета", ["ФормаВидаРасчета", "ФормаЭлемента", "ФормаСписка"]),
    "InformationRegisters": ("РегистрСведений", ["ФормаЗаписи", "ФормаСписка"]),
    "DataProcessors": ("Обработка", ["ОсновнаяФорма", "Форма"]),
    "Reports": ("Отчет", ["ОсновнаяФорма", "ФормаОтчета"]),
}

ИНТЕРЕСНЫЕ = {
    "InputField": "поле",
    "CheckBoxField": "флаг",
    "RadioButtonField": "переключатель",
    "LabelField": "надпись",
    "PictureField": "картинка",
    "Button": "кнопка",
    "Table": "таблица",
    "Column": "колонка",
    "Page": "закладка",
}


def без_ns(тег):
    return тег.rsplit("}", 1)[-1]


def найти_форму(корень_исходников, вид, имя):
    база = os.path.join(корень_исходников, вид, имя, "Forms")
    if not os.path.isdir(база):
        return None
    предпочтения = ВИДЫ[вид][1]
    формы = sorted(os.listdir(база))
    for п in предпочтения:
        if п in формы:
            путь = os.path.join(база, п, "Ext", "Form.xml")
            if os.path.exists(путь):
                return путь, п
    for ф in формы:
        путь = os.path.join(база, ф, "Ext", "Form.xml")
        if os.path.exists(путь):
            return путь, ф
    return None


def разобрать(путь_формы):
    """Обходит дерево формы и раскладывает элементы по группам."""
    дерево = ET.parse(путь_формы)
    итог = {
        "закладки": [], "поля": [], "флаги": [], "переключатели": [],
        "кнопки": [], "таблицы": {},
    }

    def обход(узел, таблица=None):
        for ребёнок in узел:
            тег = без_ns(ребёнок.tag)
            имя = ребёнок.get("name")
            if not имя:
                обход(ребёнок, таблица)
                continue
            if тег == "Table":
                итог["таблицы"].setdefault(имя, {"колонки": [], "кнопки": []})
                обход(ребёнок, имя)
                continue
            if тег in ("Column", "ColumnGroup") and таблица:
                if тег == "Column":
                    итог["таблицы"][таблица]["колонки"].append(имя)
                обход(ребёнок, таблица)
                continue
            if тег == "Button":
                (итог["таблицы"][таблица]["кнопки"] if таблица else итог["кнопки"]).append(имя)
            elif тег == "InputField":
                if not таблица:
                    итог["поля"].append(имя)
            elif тег == "CheckBoxField":
                if not таблица:
                    итог["флаги"].append(имя)
            elif тег == "RadioButtonField":
                if not таблица:
                    итог["переключатели"].append(имя)
            elif тег == "Page":
                итог["закладки"].append(имя)
            обход(ребёнок, таблица)

    обход(дерево.getroot())
    for ключ in ("закладки", "поля", "флаги", "переключатели", "кнопки"):
        итог[ключ] = список_без_повторов(итог[ключ])
    for т in итог["таблицы"].values():
        т["колонки"] = список_без_повторов(т["колонки"])
        т["кнопки"] = список_без_повторов(т["кнопки"])
    return итог


def список_без_повторов(сп):
    видели, итог = set(), []
    for э in сп:
        if э not in видели:
            видели.add(э)
            итог.append(э)
    return итог


def собрать_текст(вид, имя, форма, данные):
    тип = ВИДЫ[вид][0]
    строки = ["﻿#language: ru", ""]
    строки += [
        "# ─────────────────────────────────────────────────────────────────",
        "# КАТАЛОГ ДЕЙСТВИЙ: %s" % имя,
        "#",
        "# Это не исполняемый сценарий. Каждый «Сценарий» — одно",
        "# самостоятельное действие. Файл нужен, чтобы модель понимала,",
        "# что вообще можно сделать с этим объектом.",
        "#",
        "# ЧЕРНОВИК, СГЕНЕРИРОВАН АВТОМАТИЧЕСКИ из исходников конфигурации:",
        "#   %s\\%s\\Forms\\%s\\Ext\\Form.xml" % (вид, имя, форма),
        "# Имена настоящие, но ФАКТИЧЕСКАЯ ВИДИМОСТЬ и доступность элемента",
        "# не учтены — это покажет только прогон на живой форме.",
        "#",
        "# Объект метаданных: %s.%s" % (тип, имя),
        "# ─────────────────────────────────────────────────────────────────",
        "",
        "@каталог",
        "@НеЗапускать",
        "@черновик",
        "",
    ]

    ссылка = "e1cib/list/%s.%s" % (тип, имя)
    строки += [
        "Сценарий: Открыть список и создать новый",
        "\t# window_management(action=\"open_navigation\", navigation_link=\"%s\")" % ссылка,
        "\tИ я нажимаю на кнопку с именем 'ФормаСоздать'",
        "\t# Если кнопки нет или она недоступна — проверить функциональную",
        "\t# опцию объекта в исходниках: FunctionalOptions/<Имя>.xml, блок <Content>.",
        "",
    ]

    if данные["закладки"]:
        строки.append("Сценарий: Закладки формы")
        for з in данные["закладки"]:
            строки.append("\tИ я перехожу к закладке с именем '%s'" % з)
        строки.append("")

    if данные["поля"]:
        строки.append("Сценарий: Поля шапки")
        for п in данные["поля"]:
            строки.append("\tИ в поле с именем '%s' я ввожу текст \"\"" % п)
        строки += [
            "\t# Для ссылочных полей вместо ввода текста —",
            "\t# manage_form_elements(action=\"set_value\", exact_match=true):",
            "\t# без exact_match подстрочный поиск молча возьмёт не тот элемент.",
            "",
        ]

    if данные["флаги"]:
        строки.append("Сценарий: Флаги")
        for ф in данные["флаги"]:
            строки.append("\tИ я устанавливаю флаг с именем '%s'" % ф)
        строки.append("")

    if данные["переключатели"]:
        строки.append("Сценарий: Переключатели")
        for п in данные["переключатели"]:
            строки.append("\tИ я меняю значение переключателя с именем '%s' на \"$$Значение$$\"" % п)
        строки.append("")

    if данные["кнопки"]:
        строки.append("Сценарий: Команды формы")
        for к in данные["кнопки"]:
            строки.append("\tИ я нажимаю на кнопку с именем '%s'" % к)
        строки.append("")

    for имя_т, т in данные["таблицы"].items():
        if т["колонки"]:
            строки.append("Сценарий: Таблица «%s» — колонки" % имя_т)
            строки.append("\t# Имя таблицы: %s" % имя_т)
            строки.append("\t# Колонки: %s" % ", ".join(т["колонки"]))
            строки += [
                "\t# navigate_to_row хочет ИМЯ колонки, а не её заголовок.",
                "",
            ]
        if т["кнопки"]:
            строки.append("Сценарий: Таблица «%s» — команды" % имя_т)
            for к in т["кнопки"]:
                строки.append("\tИ в таблице \"%s\" я нажимаю на кнопку с именем '%s'" % (имя_т, к))
            строки.append("")

    строки += [
        "# ─────────────────────────────────────────────────────────────────",
        "# ЧТО ПРОВЕРИТЬ НА ЖИВОЙ ФОРМЕ, ЧТОБЫ СНЯТЬ @черновик:",
        "#   1. Открывается ли список и виден ли 'ФормаСоздать'.",
        "#   2. Какие закладки и поля реально видны (get_form_analysis).",
        "#   3. Проходит ли проведение и что пишет форма при ошибке.",
        "#   4. Есть ли печатные формы: группа 'ПодменюПечатьОбычное'.",
        "# ─────────────────────────────────────────────────────────────────",
    ]
    return "\n".join(строки) + "\n"


def main():
    p = argparse.ArgumentParser(description="Генерирует словарь действий из Form.xml")
    p.add_argument("--вид", default="Documents", choices=sorted(ВИДЫ))
    p.add_argument("--имя")
    p.add_argument("--список", help="файл со строками вида «Documents Премия»")
    p.add_argument("--исходники", default="исходники-конфигурации")
    p.add_argument("--вывод", default="drafts/словари")
    args = p.parse_args()

    задания = []
    if args.список:
        for строка in io.open(args.список, encoding="utf-8"):
            строка = строка.strip()
            if строка and not строка.startswith("#"):
                части = строка.split()
                задания.append((части[0], части[1]))
    elif args.имя:
        задания.append((args.вид, args.имя))
    else:
        p.error("нужно --имя или --список")

    сделано, пропущено = 0, []
    for вид, имя in задания:
        найдено = найти_форму(args.исходники, вид, имя)
        if not найдено:
            пропущено.append("%s.%s — не нашёл форму" % (вид, имя))
            continue
        путь, форма = найдено
        try:
            данные = разобрать(путь)
        except Exception as e:
            пропущено.append("%s.%s — не разобрался XML: %s" % (вид, имя, e))
            continue
        текст = собрать_текст(вид, имя, форма, данные)
        цель = os.path.join(args.вывод, имя + ".feature")
        io.open(цель, "w", encoding="utf-8", newline="\r\n").write(текст)
        сделано += 1
        print("%-45s <- %s (%d polej, %d knopok, %d tablic)"
              % (цель, форма, len(данные["поля"]), len(данные["кнопки"]), len(данные["таблицы"])))

    print("\nсоздано словарей: %d" % сделано)
    for п in пропущено:
        print("  пропущено:", п)
    return 0 if сделано else 1


if __name__ == "__main__":
    sys.exit(main())
