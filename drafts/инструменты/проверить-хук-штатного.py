# -*- coding: utf-8 -*-
"""Прогон хука позиции штатного расписания по сценариям.

Запуск: python drafts/инструменты/проверить-хук-штатного.py
Возвращает 1, если хотя бы один сценарий разошёлся с ожиданием.
"""
import json, os, subprocess, sys, tempfile

ХУК = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "..", "..", ".claude", "hooks", "check_staffing_fields.py")
ХУК = os.path.normpath(ХУК)
СОСТОЯНИЕ = os.path.join(tempfile.gettempdir(), "zup-agent-shr.json")
sys.stdout.reconfigure(encoding="utf-8")

ВОПРОСЫ = ["в какой организации", "в каком подразделении",
           "с какой даты утверждена", "на какую должность",
           "какой оклад", "сколько ставок"]


def вызвать(tool, args):
    payload = json.dumps({"tool_name": tool, "tool_input": args}, ensure_ascii=False)
    r = subprocess.run([sys.executable, ХУК], input=payload.encode("utf-8"),
                       capture_output=True)
    err = r.stderr.decode("utf-8", "replace").strip()
    if err:
        print("   STDERR:", err[:300])
    out = r.stdout.decode("utf-8", "replace").strip()
    return json.loads(out) if out else None


def ввод(имя):
    return ("mcp__VA__manage_form_elements",
            {"action": "set_value", "element_name": имя, "value": "x",
             "exact_match": True})


def кнопка(имя):
    return ("mcp__VA__manage_form_elements",
            {"action": "click_button", "element_name": имя})


def сброс():
    try:
        os.remove(СОСТОЯНИЕ)
    except Exception:
        pass


провалов = 0


def случай(название, шаги, ждём_вопрос, ждём=()):
    """ждём — ровно те вопросы, что должны быть перечислены."""
    global провалов
    сброс()
    ответ = None
    for tool, args in шаги:
        ответ = вызвать(tool, args)
    есть = ответ is not None
    ок = есть == ждём_вопрос
    текст = ""
    if есть:
        текст = ответ["hookSpecificOutput"]["permissionDecisionReason"]
        названо = {в for в in ВОПРОСЫ if в in текст}
        if названо != set(ждём):
            ок = False
    print(("  ок   " if ок else "  ПРОВАЛ ") + название)
    if not ок:
        провалов += 1
        print("       ответ:", (текст or "(молчит)")[:220].replace("\n", " | "))
    elif есть:
        пункты = [l.strip() for l in текст.split("\n") if l.strip().startswith("-")]
        print("       -> " + "; ".join(пункты))


ПОЛНЫЙ = ["Организация", "Подразделение", "ДатаУтверждения", "Должность",
          "Оклад", "КоличествоСтавок"]

случай("пустая позиция — спросит про пятерых (дата уже введена)",
       [ввод("ДатаУтверждения"), кнопка("КомандаОК")],
       True, [в for в in ВОПРОСЫ if в != "с какой даты утверждена"])

случай("всё заполнено — молчит",
       [ввод(и) for и in ПОЛНЫЙ] + [кнопка("КомандаОК")],
       False)

случай("нет оклада — спросит только про оклад",
       [ввод(и) for и in ПОЛНЫЙ if и != "Оклад"] + [кнопка("ФормаПровести")],
       True, ["какой оклад"])

случай("Владелец закрывает организацию",
       [ввод("Владелец"), ввод("Подразделение"), ввод("ДатаУтверждения"),
        ввод("Должность"), ввод("Оклад"), ввод("КоличествоСтавок"),
        кнопка("КомандаОК")],
       False)

случай("ДатаВступленияВСилу закрывает дату утверждения",
       [ввод("Организация"), ввод("Подразделение"), ввод("ДатаВступленияВСилу"),
        ввод("Должность"), ввод("Оклад"), ввод("КоличествоСтавок"),
        кнопка("ФормаПровестиИЗакрыть")],
       False)

случай("маркера не было — молчит, это не штатное расписание",
       [ввод("Организация"), ввод("Подразделение"), ввод("Должность"),
        кнопка("ФормаПровестиИЗакрыть")],
       False)

случай("поля введены до маркера — засчитываются",
       [ввод("Организация"), ввод("Подразделение"), ввод("Должность"),
        ввод("КоличествоСтавок"), ввод("Оклад"), ввод("ДатаУтверждения"),
        кнопка("КомандаОК")],
       False)

случай("закрыли форму — накопленное забывается",
       [ввод("Организация"), ввод("Подразделение"), кнопка("ФормаЗакрыть"),
        ввод("Оклад"), кнопка("КомандаОК")],
       True, [в for в in ВОПРОСЫ if в != "какой оклад"])

случай("поля прошлой позиции не зачтутся следующей",
       [ввод("Организация"), ввод("Оклад"), кнопка("КомандаОК"),
        ввод("Подразделение"), ввод("ДатаУтверждения"), ввод("Должность"),
        ввод("КоличествоСтавок"), кнопка("КомандаОК")],
       True, ["в какой организации", "какой оклад"])

случай("пачкой через execute_form_actions",
       [("mcp__VA__execute_form_actions",
         {"actions_json": json.dumps(
             [{"action": "set_value", "element_name": и}
              for и in ("ДатаУтверждения", "Организация", "Должность")]
             + [{"action": "click_button", "element_name": "КомандаОК"}],
             ensure_ascii=False)})],
       True, ["в каком подразделении", "какой оклад", "сколько ставок"])

случай("кнопка Записать сохранением не считается — молчит",
       [ввод("ДатаУтверждения"), кнопка("ФормаЗаписать")],
       False)

сброс()
print()
print("провалов:", провалов)
sys.exit(1 if провалов else 0)
