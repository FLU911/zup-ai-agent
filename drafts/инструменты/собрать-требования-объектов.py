# -*- coding: utf-8 -*-
"""Собирает таблицу обязательных полей для хука check_object_fields.py.

Читает словари действий (drafts/словари/*.feature) и для каждого объекта
метаданных выписывает, чем нельзя не заполнить его карточку. Имена полей
берутся ТОЛЬКО из словарей и только из секций шапки — придумывать их
нельзя (жёсткое правило 1 в CLAUDE.md), а поля табличных частей на роль
обязательных не годятся: они заполняются построчно.

Правило простое и одинаковое для всех:
  документ    — организация, дата документа и тот, по кому документ,
                если такое поле есть в шапке;
  справочник  — наименование (у физических лиц оно называется ФИО).

Результат: .claude/hooks/требования-объектов.json

Запуск:  python drafts/инструменты/собрать-требования-объектов.py
"""
import io
import json
import os
import re
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
# Словари лежат в двух местах: общий черновой каталог и рядом со скиллом
# той операции, которая этим объектом занимается.
СЛОВАРИ = (os.path.join(КОРЕНЬ, "drafts", "словари"),
           os.path.join(КОРЕНЬ, ".claude", "skills"))
ВЫХОД = os.path.join(КОРЕНЬ, ".claude", "hooks", "требования-объектов.json")

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

ИМЯ = re.compile(r"с именем '([^']+)'")
ОБЪЕКТ = re.compile(r"Объект метаданных:\s*(\S+)")
СЦЕНАРИЙ = re.compile(r"^\s*Сценарий:\s*(.+?)\s*$")

# Секции словаря, откуда берём имена: «Поля шапки», «Заполнить поля
# шапки», «Заполнить шапку документа». Всё, что про таблицы, закладки
# и команды, сюда не попадает — обязательным может быть только поле шапки.
ШАПКА = ("шапк", "снятые с живой формы")

# Словари, где объект назван не строкой «Объект метаданных», а в общем
# заголовке: перечислены несколько форм одного объекта. Имена в таких
# файлах в секции шапки не лежат, поэтому берём их из всего файла.
ЗАГОЛОВОК_НЕ_РАЗОБРАН = {
    "СотрудникиЛичныеДанные.feature": "Справочник.Сотрудники",
}

# Объекты со своим отдельным хуком: там проверка тоньше, чем общая,
# и два хука подряд задали бы человеку одни и те же вопросы дважды.
СВОИ_ХУКИ = {
    "Документ.ПриемНаРаботу": "check_hiring_fields.py",
    "Документ.ИзменениеШтатногоРасписания": "check_staffing_fields.py",
    "Справочник.ШтатноеРасписание": "check_staffing_fields.py",
    "Документ.УтверждениеШтатногоРасписания": "check_staffing_fields.py",
}

# Вопрос человеку → имена, любое из которых его закрывает. Берём только
# те имена, которые есть в шапке конкретного объекта.
ТРЕБОВАНИЯ_ДОКУМЕНТА = (
    ("в какой организации", ("Организация", "ОрганизацияПлательщик",
                             "НоваяОрганизация", "ТекущаяОрганизация",
                             "Владелец")),
    ("дата документа", ("Дата", "ДатаДокумента")),
    ("по кому документ", ("Сотрудник", "ФизическоеЛицо", "Работник",
                          "Контрагент")),
    ("за какой месяц", ("МесяцНачисления", "МесяцНачисленияСтрокой",
                        "ПериодРегистрации", "Месяц")),
)

ТРЕБОВАНИЯ_СПРАВОЧНИКА = (
    ("наименование", ("Наименование", "ФИО", "НаименованиеПолное")),
    ("в какой организации", ("Организация", "Владелец")),
)


def поля_шапки(текст):
    """Имена элементов из секций шапки словаря."""
    найдено = []
    берём = False
    for строка in текст.splitlines():
        m = СЦЕНАРИЙ.match(строка)
        if m:
            берём = any(к in m.group(1).lower() for к in ШАПКА)
            continue
        if берём:
            найдено.extend(ИМЯ.findall(строка))
    return найдено


def словари():
    """Пути ко всем файлам словарей, в порядке имени файла."""
    найдено = []
    for корень in СЛОВАРИ:
        for каталог, _, файлы in os.walk(корень):
            for файл in файлы:
                if файл.endswith(".feature"):
                    найдено.append(os.path.join(каталог, файл))
    return sorted(найдено, key=lambda п: os.path.basename(п))


def собрать():
    таблица = {}
    пропущено = []
    for путь in словари():
        файл = os.path.relpath(путь, КОРЕНЬ)
        текст = io.open(путь, encoding="utf-8-sig").read()
        особый = ЗАГОЛОВОК_НЕ_РАЗОБРАН.get(os.path.basename(путь))
        m = ОБЪЕКТ.search(текст)
        if особый:
            объект = особый
        elif m:
            объект = m.group(1)
        else:
            пропущено.append((файл, "нет строки «Объект метаданных»"))
            continue
        вид = объект.split(".")[0]
        if вид == "Документ":
            правила = ТРЕБОВАНИЯ_ДОКУМЕНТА
        elif вид == "Справочник":
            правила = ТРЕБОВАНИЯ_СПРАВОЧНИКА
        else:
            пропущено.append((файл, "вид объекта «%s» не проверяем" % вид))
            continue
        if объект in СВОИ_ХУКИ:
            пропущено.append((файл, "свой хук: " + СВОИ_ХУКИ[объект]))
            continue

        шапка = set(ИМЯ.findall(текст) if особый else поля_шапки(текст))
        группы = []
        for вопрос, имена in правила:
            есть = [и for и in имена if и in шапка]
            if есть:
                группы.append([вопрос, есть])
        if not группы:
            пропущено.append((файл, "в шапке нет ни одного поля из правил"))
            continue
        таблица[объект] = {"словарь": файл.replace("\\", "/"),
                           "требуется": группы}
    return таблица, пропущено


def main():
    таблица, пропущено = собрать()
    io.open(ВЫХОД, "w", encoding="utf-8").write(
        json.dumps({"объекты": таблица}, ensure_ascii=False, indent=1,
                   sort_keys=True))
    print("объектов в таблице: %d  →  %s" % (len(таблица), ВЫХОД))
    свод = {}
    for объект, данные in таблица.items():
        ключ = tuple(в for в, _ in данные["требуется"])
        свод.setdefault(ключ, []).append(объект)
    for ключ, объекты in sorted(свод.items(), key=lambda п: -len(п[1])):
        print("  %3d  %s" % (len(объекты), " + ".join(ключ)))
        if len(объекты) <= 5:
            for о in объекты:
                print("         %s" % о)
    print("\nне попало (%d):" % len(пропущено))
    for файл, почему in пропущено:
        print("  %-55s %s" % (файл[:-8], почему))


if __name__ == "__main__":
    main()
