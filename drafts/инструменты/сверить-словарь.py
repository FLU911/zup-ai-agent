# -*- coding: utf-8 -*-
"""
Сверка словаря с живой формой и снятие тега @черновик.

Словарь, сгенерированный из Form.xml, знает имена, но не знает, что
из этого реально показывает форма. Сверка закрывает эту дыру: на вход
подаётся список имён, снятых с ЖИВОЙ формы (`get_form_analysis`),
на выходе — тот же словарь с блоком «ПРОВЕРЕНО ВЖИВУЮ», где видно:

  * какие имена словаря форма подтвердила;
  * какие имена словарь обещает, а форма не показывает
    (скрыты функциональной опцией, состоянием объекта или правами);
  * какие имена форма показывает, а словарь не знает.

Тег `@черновик` снимается только если форма вообще открылась и хотя бы
что-то подтвердила. Всё остальное — повод оставить черновик как есть.

Запуск:

    python сверить-словарь.py --словарь drafts/словари/Должности.feature \\
        --живые живые-имена.txt --что "Справочник.Должности, форма элемента"

`живые-имена.txt` — просто по имени в строке; удобно получать так:
`get_form_analysis(format="gherkin")` и вытащить имена регуляркой.
"""

import argparse
import io
import os
import re
import sys
from datetime import date


def имена_словаря(текст):
    имена = set()
    имена |= set(re.findall(r"с именем '([^']+)'", текст))
    имена |= set(re.findall(r"закладке с именем '([^']+)'", текст))
    for строка in re.findall(r"# Колонки: (.+)", текст):
        имена |= {к.strip() for к in строка.split(",") if к.strip()}
    return имена


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--словарь", required=True)
    p.add_argument("--живые", required=True, help="файл с именами, снятыми с живой формы")
    p.add_argument("--что", default="", help="что именно открывали: объект и форма")
    p.add_argument("--заметка", default="", help="строка-другая от руки: что выяснилось")
    p.add_argument("--выборочно", action="store_true",
                   help="в файле не весь состав формы, а только проверенные имена: "
                        "тогда про остальные имена словаря ничего не утверждаем")
    args = p.parse_args()

    текст = io.open(args.словарь, encoding="utf-8").read()
    словарь = имена_словаря(текст)
    живые = {с.strip() for с in io.open(args.живые, encoding="utf-8") if s_ok(s := s_strip(с))}

    подтверждено = sorted(словарь & живые)
    только_в_словаре = sorted(словарь - живые)
    только_на_форме = sorted(живые - словарь)

    блок = [
        "",
        "# ═════════════════════════════════════════════════════════════════",
        "# ПРОВЕРЕНО ВЖИВУЮ %s." % date.today().strftime("%d.%m.%Y"),
        "# Открыто: %s" % (args.что or "форма объекта"),
        "#",
        "# Форма подтвердила имён: %d из %d, которые обещает словарь." % (len(подтверждено), len(словарь)),
    ]
    if только_в_словаре and args.выборочно:
        блок += [
            "#",
            "# Сверка ВЫБОРОЧНАЯ: снят не весь состав формы, а ключевые имена.",
            "# Про остальные %d имени словаря сверка ничего не утверждает —" % len(только_в_словаре),
            "# они могут быть на форме, а могут быть скрыты. Проверять на месте.",
        ]
    elif только_в_словаре:
        блок += [
            "#",
            "# ЕСТЬ В СЛОВАРЕ, НО ФОРМА НЕ ПОКАЗАЛА (%d). Это не ошибка имён:" % len(только_в_словаре),
            "# элемент скрыт функциональной опцией, состоянием объекта или",
            "# правами. Перед использованием проверять get_form_element_data.",
        ]
        for и in (только_в_словаре[:40] if not args.выборочно else []):
            блок.append("#   %s" % и)
        if len(только_в_словаре) > 40 and not args.выборочно:
            блок.append("#   ... и ещё %d" % (len(только_в_словаре) - 40))
    if только_на_форме:
        блок += [
            "#",
            "# ЕСТЬ НА ФОРМЕ, НО НЕ БЫЛО В СЛОВАРЕ (%d) — дописаны ниже:" % len(только_на_форме),
        ]
        for и in только_на_форме[:40]:
            блок.append("#   %s" % и)
        if len(только_на_форме) > 40:
            блок.append("#   ... и ещё %d" % (len(только_на_форме) - 40))
    if args.заметка:
        блок += ["#", "# " + args.заметка.replace("\n", "\n# ")]
    блок += ["# ═════════════════════════════════════════════════════════════════", ""]

    if только_на_форме:
        блок += ["Сценарий: Элементы, снятые с живой формы"]
        for и in только_на_форме:
            блок.append("\tИ элемент формы с именем '%s' существует" % и)
        блок.append("")

    # снимаем черновик, только если форма что-то подтвердила
    if подтверждено:
        текст = текст.replace("@черновик\n", "@проверено\n", 1)

    io.open(args.словарь, "w", encoding="utf-8", newline="").write(текст.rstrip("\n") + "\n" + "\n".join(блок))
    print("%s: подтверждено %d, только в словаре %d, только на форме %d, черновик %s"
          % (os.path.basename(args.словарь), len(подтверждено), len(только_в_словаре),
             len(только_на_форме), "снят" if подтверждено else "оставлен"))
    return 0


def s_strip(с):
    return с.strip()


def s_ok(с):
    return bool(с) and not с.startswith("#")


if __name__ == "__main__":
    sys.exit(main())
