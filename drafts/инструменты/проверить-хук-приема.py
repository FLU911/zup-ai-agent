# -*- coding: utf-8 -*-
"""Прогон хука приёма на работу по сценариям."""
import json, os, subprocess, sys, tempfile

ХУК = r"C:\claude\zup-ai-agent\.claude\hooks\check_hiring_fields.py"
СОСТОЯНИЕ = os.path.join(tempfile.gettempdir(), "zup-agent-priem.json")
sys.stdout.reconfigure(encoding="utf-8")


def вызвать(tool, args):
    payload = json.dumps({"tool_name": tool, "tool_input": args}, ensure_ascii=False)
    r = subprocess.run([sys.executable, ХУК], input=payload.encode("utf-8"),
                       capture_output=True)
    err = r.stderr.decode("utf-8", "replace").strip()
    if err:
        print("   STDERR:", err[:300])
    out = r.stdout.decode("utf-8", "replace").strip()
    if not out:
        return None
    return json.loads(out)


def ввод(имя):
    return ("mcp__VA__manage_form_elements",
            {"action": "set_value", "element_name": имя, "value": "x",
             "exact_match": True})


def кнопка(имя):
    return ("mcp__VA__manage_form_elements",
            {"action": "click_button", "element_name": имя})


def сброс():
    try:
        os.remove(СОСТОЯНИЕ)
    except Exception:
        pass


провалов = 0


ВСЕ_ПОЛЯ = ["Сотрудник", "Должность", "Подразделение", "Организация",
            "График", "ДатаПриема"]


def случай(название, шаги, ждём_вопрос, ждём_поля=()):
    """ждём_поля — ровно те, что должны быть перечислены, остальных быть не должно."""
    global провалов
    сброс()
    ответ = None
    for tool, args in шаги:
        ответ = вызвать(tool, args)
    есть_вопрос = ответ is not None
    ок = есть_вопрос == ждём_вопрос
    текст = ""
    if есть_вопрос:
        текст = ответ["hookSpecificOutput"]["permissionDecisionReason"]
        перечислено = {п for п in ВСЕ_ПОЛЯ if "(%s)" % п in текст}
        if перечислено != set(ждём_поля):
            ок = False
    print(("  ок   " if ок else "  ПРОВАЛ ") + название)
    if not ок:
        провалов += 1
        print("       ответ:", (текст or "(молчит)")[:200].replace("\n", " | "))
    elif есть_вопрос:
        первая = текст.split("\n")[0]
        поля = [l.strip() for l in текст.split("\n") if l.strip().startswith("-")]
        print("       -> " + первая + "  " + "; ".join(поля))


ВСЕ = ["Сотрудник", "Должность", "Подразделение", "Организация", "График", "ДатаПриема"]

