"""Прогон общего хука обязательных полей (check_object_fields.py).

Ничего не открывает и в базу не ходит: подсовывает хуку такие же
JSON-пакеты, какие ему шлёт Claude Code, и смотрит на решение.
Запускать после любой правки хука или таблицы требований.
"""
import json
import os
import subprocess
import sys
import tempfile

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ХУК = os.path.join(КОРЕНЬ, ".claude", "hooks", "check_object_fields.py")
СОСТОЯНИЕ = os.path.join(tempfile.gettempdir(), "zup-agent-object.json")

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass


def вызвать(tool, args):
    payload = json.dumps({"tool_name": tool, "tool_input": args},
                         ensure_ascii=False)
    r = subprocess.run([sys.executable, ХУК], input=payload.encode("utf-8"),
                       capture_output=True)
    err = r.stderr.decode("utf-8", "replace").strip()
    if err:
        print("   STDERR:", err[:300])
    out = r.stdout.decode("utf-8", "replace").strip()
    return json.loads(out) if out else None


def открыть(объект):
    return ("mcp__VA__window_management",
            {"action": "open_navigation",
             "navigation_link": "e1cib/list/%s" % объект})


def ввод(имя, таблица=None):
    args = {"action": "set_value", "element_name": имя, "value": "x",
            "exact_match": True}
    if таблица:
        args["table_name"] = таблица
    return ("mcp__VA__manage_form_elements", args)


def прочитать(имя):
    return ("mcp__VA__get_form_element_data", {"element_name": имя})


def кнопка(имя):
    return ("mcp__VA__manage_form_elements",
            {"action": "click_button", "element_name": имя})


def сброс():
    try:
        os.remove(СОСТОЯНИЕ)
    except Exception:
        pass


провалов = 0


def случай(название, шаги, ждём_вопрос, ждём_поля=()):
    """ждём_поля — вопросы, которые должны быть перечислены, и только они."""
    global провалов
    сброс()
    ответ = None
    for tool, args in шаги:
        ответ = вызвать(tool, args)
    есть_вопрос = ответ is not None
    ок = есть_вопрос == ждём_вопрос
    текст = ""
    if есть_вопрос:
        текст = ответ["hookSpecificOutput"]["permissionDecisionReason"]
        перечислено = {с.strip()[2:].split(" (")[0]
                       for с in текст.split("\n") if с.strip().startswith("- ")}
        if перечислено != set(ждём_поля):
            ок = False
    print(("  ок      " if ок else "  ПРОВАЛ  ") + название)
    if not ок:
        провалов += 1
        print("          ответ:", (текст or "(молчит)")[:300].replace("\n", " | "))
    elif есть_вопрос:
        первая = текст.split("\n")[0]
        поля = [с.strip() for с in текст.split("\n") if с.strip().startswith("- ")]
        print("          -> " + первая + "  " + "; ".join(поля))


