# Разбор аргументов ВНЕ try: иначе опечатка в обвязке выглядит как
# срабатывание плагина, и сверка радостно врёт про расхождение.
JS_ОБВЯЗКА = """
import { ObjectFields } from %s
const шаги = JSON.parse(process.argv[process.argv.length - 1])
const плагин = await ObjectFields({})
let итог = "PASS"
for (const [tool, args] of шаги) {
  итог = "PASS"
  try {
    await плагин["tool.execute.before"]({ tool: "va_" + tool }, { args })
  } catch (e) {
    итог = "ASK"
  }
}
console.log(итог)
"""


def сброс():
    try:
        os.remove(СОСТОЯНИЕ)
    except Exception:
        pass


def через_питон(цепочка):
    сброс()
    итог = "PASS"
    for инструмент, аргументы in цепочка:
        вход = json.dumps({"tool_name": "mcp__VA__" + инструмент,
                           "tool_input": аргументы}, ensure_ascii=False)
        п = subprocess.run([sys.executable, ХУК], input=вход.encode("utf-8"),
                           stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        вывод = п.stdout.decode("utf-8", "replace").strip()
        итог = "PASS"
        if вывод:
            ответ = json.loads(вывод)
            решение = ответ.get("hookSpecificOutput", {}).get("permissionDecision")
            итог = "ASK" if решение == "ask" else "PASS"
    return итог, ""


def через_node(цепочка):
    сброс()
    # На Windows ESM-загрузчик node принимает только file:// — обычный
    # путь вида C:\... он считает протоколом «c:» и падает.
    ссылка = json.dumps(pathlib.Path(ПЛАГИН).as_uri())
    скрипт = JS_ОБВЯЗКА % ссылка
    п = subprocess.run(["node", "--input-type=module", "-e", скрипт, "--",
                        json.dumps(цепочка, ensure_ascii=False)],
                       stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    вывод = п.stdout.decode("utf-8", "replace").strip()
    if вывод not in ("PASS", "ASK"):
        строки = п.stderr.decode("utf-8", "replace").strip().split("\n")
        внятные = [с for с in строки if "Error" in с or "error" in с]
        return "ОШИБКА", (внятные or строки or ["node молчит"])[0].strip()
    return вывод, ""


def главная():
    for путь in (ХУК, ПЛАГИН):
        if not os.path.exists(путь):
            print("Не найден файл: %s" % путь)
            return 1

    расхождений = 0
    print("%-46s %-8s %-8s %s" % ("случай", "python", "node", "итог"))
    print("-" * 80)

    for описание, цепочка, ждём_вопрос in СЛУЧАИ:
        п_решение, _ = через_питон(цепочка)
        н_решение, ошибка = через_node(цепочка)
        ожидание = "ASK" if ждём_вопрос else "PASS"

        if н_решение == "ОШИБКА":
            итог = "node не запустился: " + ошибка
            расхождений += 1
        elif п_решение != н_решение:
            итог = "РАСХОЖДЕНИЕ"
            расхождений += 1
        elif п_решение != ожидание:
            итог = "обе не так, ждали " + ожидание
            расхождений += 1
        else:
            итог = "ок"

        print("%-46s %-8s %-8s %s" % (описание[:46], п_решение, н_решение, итог))

    сброс()
    print()
    if расхождений:
        print("Расхождений: %d. Копии разъехались — править обе." % расхождений)
        return 1
    print("Обе копии согласны на всех %d случаях." % len(СЛУЧАИ))
    return 0


if __name__ == "__main__":
    sys.exit(главная())
