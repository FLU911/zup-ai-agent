# -*- coding: utf-8 -*-
"""
Конвертер исполняемого сценария Vanessa в словарь действий.

Обратная задача к `сгенерировать-словарь.py`. Тот делает словарь из
исходников конфигурации: имена настоящие, но что из них реально видно
на форме — неизвестно. Этот делает словарь из ПРОГНАННОГО сценария, а
раз сценарий прошёл зелёным, каждое имя в нём подтверждено живой
формой. Это самый надёжный источник словаря, какой есть в проекте.

Что выбрасывается — машинерия контракта результата, в словаре её нет:

    Попытка / Исключение          вместе со всей веткой Исключение
    Я запоминаю значение выражения '{"success": ...}'
    Затем я останавливаю выполнение сценариев данной фичи
    @tree и прочие теги запуска

Что сохраняется: шаги действий, проверки «Тогда ...», блоки
«Если ... Тогда» вместе с вложенным телом, переменные вида $$Имя$$
и комментарии автора сценария.

Каждая группа шагов `*название` становится отдельным «Сценарием»
словаря, то есть одним самостоятельным действием. Групп нет — сценарий
переносится одним блоком.

Запуск:

    python сценарий-в-словарь.py --фича authoring/features/01_ПриемНаРаботу.feature
    python сценарий-в-словарь.py --фича X.feature --прогнан --вывод drafts/словари
    python сценарий-в-словарь.py --фича X.feature --имя "Приём на работу" --объект Документ.ПриемНаРаботу

По умолчанию результат кладётся в `drafts/tmp/` и помечается
`@черновик`: пока не сказано `--прогнан`, неизвестно, видел ли кто-то
эти имена на живой форме. Правило проекта — словарь без подтверждения
в `drafts/словари/` не кладут.
"""

import argparse
import io
import os
import re
import sys

# ── что выбрасываем ──────────────────────────────────────────────────
МУСОР = (
    # контракт результата: строка со «значением выражения» — это JSON
    # {"success": ...}, который читает агент. Значение ПОЛЯ, наоборот,
    # настоящее действие и остаётся.
    re.compile(r"^запоминаю значение выражения", re.I),
    re.compile(r"^останавливаю выполнение сценариев", re.I),
    re.compile(r"^прерываю цикл$", re.I),
)

СОЮЗЫ = re.compile(r"^(?:И|А|Дано|Когда|Тогда|Затем)\s+", re.I)
МЕСТОИМЕНИЕ = re.compile(r"^Я\s+", re.I)

# «откроем форму» → «Открыть форму»: сценарий пишут от первого лица
# множественного числа, словарь — неопределённой формой.
ГЛАГОЛЫ = {
    "откроем": "открыть", "закроем": "закрыть", "заполним": "заполнить",
    "проведем": "провести", "проведём": "провести", "проверим": "проверить",
    "установим": "установить", "сформируем": "сформировать",
    "выберем": "выбрать", "создадим": "создать", "добавим": "добавить",
    "запишем": "записать", "сохраним": "сохранить", "введем": "ввести",
    "введём": "ввести", "нажмем": "нажать", "нажмём": "нажать",
    "перейдем": "перейти", "перейдём": "перейти", "укажем": "указать",
    "снимем": "снять", "прочитаем": "прочитать", "найдем": "найти",
    "найдём": "найти", "удалим": "удалить", "отменим": "отменить",
    "выгрузим": "выгрузить", "загрузим": "загрузить", "распечатаем": "распечатать",
}


def отступ(строка):
    """Глубина отступа в «табах»: четыре пробела считаем за таб."""
    голая = строка.lstrip("\t ")
    префикс = строка[:len(строка) - len(голая)]
    return префикс.count("\t") + префикс.count(" ") // 4


def без_союза(текст):
    """«И Я запоминаю…» → «запоминаю…», чтобы сравнивать с мусором."""
    м = СОЮЗЫ.match(текст)
    текст = текст[м.end():] if м else текст
    м = МЕСТОИМЕНИЕ.match(текст)
    return текст[м.end():] if м else текст


def назвать(группа):
    """«заполним оплату труда» → «Заполнить оплату труда»."""
    слова = группа.split()
    if слова:
        замена = ГЛАГОЛЫ.get(слова[0].lower())
        if замена:
            слова[0] = замена
    готово = " ".join(слова)
    return готово[:1].upper() + готово[1:]


def это_мусор(текст):
    голый = без_союза(текст.strip())
    return any(р.search(голый) for р in МУСОР)


def прочитать(путь):
    with io.open(путь, encoding="utf-8-sig") as ф:
        return ф.read().replace("\r\n", "\n").split("\n")


def разобрать(строки):
    """Возвращает (заголовок фичи, строки контекста, [(имя группы, шаги)])."""
    заголовок = ""
    контекст = []
    группы = []
    текущая = None
    в_контексте = False
    в_сценарии = False

    for сырая in строки:
        текст = сырая.strip()
        глубина = отступ(сырая)

        if not текст or текст.startswith("#language") or текст.startswith("@"):
            continue

        м = re.match(r"^(?:Функционал|Функция|Feature):\s*(.*)$", текст, re.I)
        if м:
            заголовок = м.group(1).strip()
            в_контексте = в_сценарии = False
            continue

        if re.match(r"^(?:Контекст|Background):", текст, re.I):
            в_контексте, в_сценарии = True, False
            continue

        м = re.match(r"^(?:Сценарий|Scenario)(?:\s+структуры)?:\s*(.*)$", текст, re.I)
        if м:
            в_контексте = False
            в_сценарии = True
            текущая = (м.group(1).strip(), [])
            группы.append(текущая)
            continue

        if в_контексте:
            контекст.append(текст)
            continue

        if not в_сценарии:
            continue

        # группа шагов внутри сценария: строка вида «*заполним шапку»
        if текст.startswith("*"):
            текущая = (текст.lstrip("*").strip(), [])
            группы.append(текущая)
            continue

        if текущая is not None:
            текущая[1].append((глубина, текст))

    return заголовок, контекст, группы


def очистить(шаги):
    """Убирает Попытка/Исключение и контракт, выравнивает отступы."""
    отобранные = []
    пропускать_до = None      # глубина ветки Исключение

    for глубина, текст in шаги:
        if пропускать_до is not None:
            if глубина > пропускать_до:
                continue
            пропускать_до = None

        голый = текст.strip()

        if re.match(r"^Исключение$", голый, re.I):
            пропускать_до = глубина
            continue
        if re.match(r"^Попытка$", голый, re.I):
            continue
        if это_мусор(голый):
            continue

        отобранные.append((глубина, голый))

    if not отобранные:
        return []

    минимум = min(г for г, _ in отобранные)
    return ["\t" * (1 + г - минимум) + т for г, т in отобранные]


def угадать_объект(группы):
    for _, шаги in группы:
        for _, текст in шаги:
            м = re.search(r'основную форму (?:списка )?документа\s+"([^"]+)"', текст, re.I)
            if м:
                return "Документ." + м.group(1)
            м = re.search(r'основную форму (?:списка )?справочника\s+"([^"]+)"', текст, re.I)
            if м:
                return "Справочник." + м.group(1)
            м = re.search(r"e1cib/(?:list|data)/([A-Za-zА-Яа-я]+\.[A-Za-zА-Яа-я_]+)", текст)
            if м:
                return м.group(1)
    return ""


def шапка(имя, объект, источник, прогнан, контекст):
    черта = "# " + "─" * 63
    строки = [
        "#language: ru",
        "",
        черта,
        "# КАТАЛОГ ДЕЙСТВИЙ: %s" % имя,
        "#",
        "# Это не исполняемый сценарий. Каждый «Сценарий» — одно",
        "# самостоятельное действие. Файл нужен, чтобы модель понимала,",
        "# что вообще можно сделать с этим объектом.",
        "#",
        "# СДЕЛАН ИЗ ИСПОЛНЯЕМОГО СЦЕНАРИЯ:",
        "#   %s" % источник,
        "#",
    ]
    if прогнан:
        строки += [
            "# Сценарий прогнан на живой базе и прошёл зелёным, поэтому имена",
            "# ниже подтверждены живой формой — это надёжнее имён, снятых",
            "# из исходников конфигурации.",
            "#",
        ]
    else:
        строки += [
            "# ЧЕРНОВИК: сценарий-источник на живой базе НЕ прогонялся, имена",
            "# формой не подтверждены. По правилам проекта такой словарь",
            "# в drafts/словари/ не кладут — сначала прогон или сверка",
            "# (drafts/инструменты/сверить-словарь.py).",
            "#",
        ]
    if объект:
        строки += ["# Объект метаданных: %s" % объект, "#"]
    if контекст:
        строки += [
            "# Контекст сценария-источника — в словаре не исполняется,",
            "# но помнить о нём надо:",
        ]
        строки += ["#   %s" % с for с in контекст]
        строки += ["#"]
    строки += [
        "# Что доделать руками, конвертер этого не знает:",
        "#   1. Полнота: сценарий покрывал одну операцию, а словарь описывает",
        "#      объект целиком — чего не хватает, видно только человеку.",
        "#   2. Видимость: что скрыто на новом документе и появляется",
        "#      только после записи.",
        "#   3. Печатные формы: группа 'ПодменюПечатьОбычное'.",
        черта,
        "",
        "@каталог",
        "@НеЗапускать",
    ]
    if not прогнан:
        строки.append("@черновик")
    строки += ["", "Функционал: %s — что можно сделать с объектом" % имя, ""]
    return строки


def главная(а):
    строки = прочитать(а.фича)
    заголовок, контекст, группы = разобрать(строки)

    if not группы:
        print("В файле не нашлось ни одного сценария — конвертировать нечего.")
        return 1

    имя = а.имя or заголовок or os.path.splitext(os.path.basename(а.фича))[0]
    объект = а.объект or угадать_объект(группы)

    тело = []
    сценариев = 0
    пустых = 0
    for название, шаги in группы:
        готовые = очистить(шаги)
        if not готовые:
            пустых += 1
            continue
        тело.append("Сценарий: " + назвать(название))
        тело.extend(готовые)
        тело.append("")
        сценариев += 1

    if not тело:
        print("После вычистки машинерии не осталось ни одного шага.")
        return 1

    вывод = шапка(имя, объект, а.фича.replace("\\", "/"), а.прогнан, контекст) + тело

    папка = а.вывод or ("drafts/словари" if а.прогнан else "drafts/tmp")
    if not os.path.isdir(папка):
        os.makedirs(папка)
    путь = os.path.join(папка, (а.файл or имя.replace(" ", "")) + ".feature")

    if os.path.exists(путь) and not а.перезаписать:
        print("Файл уже есть: %s" % путь)
        print("Добавьте --перезаписать, если это осознанно.")
        return 1

    with io.open(путь, "w", encoding="utf-8-sig", newline="\r\n") as ф:
        ф.write("\n".join(вывод).rstrip() + "\n")

    print("Готово: %s" % путь)
    print("Сценариев в словаре: %d%s" % (
        сценариев, (", пустых групп пропущено: %d" % пустых) if пустых else ""))
    if not а.прогнан:
        print("Помечен @черновик. В drafts/словари/ класть только после прогона или сверки.")
    return 0


if __name__ == "__main__":
    р = argparse.ArgumentParser(description="Сценарий Vanessa → словарь действий")
    р.add_argument("--фича", required=True, help="исходный feature-файл")
    р.add_argument("--вывод", help="куда положить (по умолчанию drafts/tmp или drafts/словари)")
    р.add_argument("--файл", help="имя файла без расширения")
    р.add_argument("--имя", help="название объекта для заголовка")
    р.add_argument("--объект", help="объект метаданных, например Документ.ПриемНаРаботу")
    р.add_argument("--прогнан", action="store_true",
                   help="сценарий прошёл на живой базе: имена подтверждены, @черновик не ставится")
    р.add_argument("--перезаписать", action="store_true")
    sys.exit(главная(р.parse_args()))
